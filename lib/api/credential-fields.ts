// path: lib/api/credential-fields.ts
import type { PlatformRole } from "../auth/types.ts";

/**
 * Section 20's vocabulary for a merchant API credential, in the one module both the browser and the server
 * may import.
 *
 * The rule this file exists to serve is the section's third sentence: *"Full API keys and secrets are never
 * displayed. After creation they are shown masked only and never appear in UI, logs or error messages."*
 * Everything a screen is allowed to know is named here - a mode, a status, a prefix, the last four
 * characters - and there is deliberately no type in this module that can hold a whole key.
 */

/** The table `0034` created, which this STEP writes and never alters. */
export const MERCHANT_API_CREDENTIALS_TABLE = "merchant_api_credentials";

/** The audit entity name of one credential. */
export const CREDENTIAL_ENTITY = "merchant_api_credential";

/** The two modes of section 8: a merchant keeps its test keys and its live keys apart. */
export const CREDENTIAL_MODES = Object.freeze(["test", "live"] as const);

export type CredentialMode = (typeof CREDENTIAL_MODES)[number];

/** Whether a word is one of the two modes. */
export function isCredentialMode(value: unknown): value is CredentialMode {
  return value === "test" || value === "live";
}

/** The two states a credential can be in. Revoking is STEP 201's act; this STEP only ever writes `active`. */
export const CREDENTIAL_STATUSES = Object.freeze(["active", "revoked"] as const);

export type CredentialStatus = (typeof CREDENTIAL_STATUSES)[number];

/** The only roles that may see or create a merchant's own credentials. */
export const CREDENTIAL_ROLES: readonly PlatformRole[] = Object.freeze(["owner"] as const satisfies readonly PlatformRole[]);

/** The first component of every key this platform issues. */
export const CREDENTIAL_KEY_PREFIX = "kd";

/**
 * The shape of a key, as a pattern rather than as a value.
 *
 * `kd_<mode>_<handle>_<64 hex characters>`: the mode is visible so a test key cannot be mistaken for a live
 * one, the handle is what a screen shows, and the 64 hex characters are 32 random bytes. `0034` bounds the
 * handle to `^[a-z][a-z0-9_]{1,15}$` and the last four characters to `^[A-Za-z0-9]{4}$`, and this pattern is
 * the whole key those two columns are cut from.
 */
export const CREDENTIAL_KEY_PATTERN = /^kd_(?:test|live)_[a-z][a-z0-9_]{1,15}_[0-9a-f]{64}$/u;

/** The handle's own pattern, which is `merchant_api_credentials_prefix_check` in `0034`. */
export const CREDENTIAL_HANDLE_PATTERN = /^[a-z][a-z0-9_]{1,15}$/u;

/** The hash and the tails `0034` accepts. */
export const CREDENTIAL_HASH_PATTERN = /^[0-9a-f]{64}$/u;
export const CREDENTIAL_TAIL_PATTERN = /^[A-Za-z0-9]{4}$/u;

/** How many random bytes go into a key and into the webhook signing secret: 32, or 64 hex characters. */
export const CREDENTIAL_SECRET_BYTES = 32;

/** The character a masked display is built from, so a screen and the gate agree on what "masked" looks like. */
export const CREDENTIAL_MASK = "\u2022";

/** How many mask characters stand between the prefix and the last four. */
export const CREDENTIAL_MASK_WIDTH = 8;

/** The longest label a merchant may give a credential, which `0034` also checks. */
export const CREDENTIAL_LABEL_MAXIMUM_LENGTH = 80;

/**
 * How many live credentials one merchant may hold per mode.
 *
 * `0034` has no such limit, and it should not: a row limit is a product decision that can change without a
 * migration. Ten is enough for a shop with a checkout, a subscription service and a handful of old
 * integrations, and small enough that a runaway script cannot fill the table with one merchant's keys.
 */
export const CREDENTIAL_ACTIVE_LIMIT = 10;

/** How many rows the screen reads, newest first. */
export const CREDENTIAL_HISTORY_LIMIT = 50;

/** The body ceiling of the one route this STEP writes. */
export const CREDENTIAL_MAXIMUM_BODY_BYTES = 1_024;

/**
 * The associated data the signing secret is sealed under.
 *
 * `0034` stores the secret as AES-256-GCM ciphertext, so an attacker who copies the three columns into
 * another merchant's row gets a box that will not open: the tenant is authenticated by the seal itself. The
 * credential's own id cannot be in here, because the row's id is generated by the database default and the
 * ciphertext is written in the same insert - which is why the company, and not the credential, is the scope.
 */
export const CREDENTIAL_SECRET_CONTEXT_PREFIX = "kd-aad-v1|merchant_api_credential";

/** The associated data of one merchant's credentials. */
export function credentialSecretContext(companyId: string): string {
  return `${CREDENTIAL_SECRET_CONTEXT_PREFIX}|${companyId}`;
}

/**
 * The refusals a screen may print as a sentence.
 *
 * Machine words rather than English: the message layer owns the sentence, and a rule is what a client
 * branches on. They are exported frozen so the gate can assert that the service and the screen name the same
 * ones rather than two spellings of the same idea.
 */
export const CREDENTIAL_RULES = Object.freeze({
  /** The body is not `{ label, mode }`. */
  invalidFormat: "invalid_format",
  /** The label is empty, blank or longer than eighty characters. */
  labelInvalid: "label_invalid",
  /** This merchant already has a live credential with that label, in any mode. */
  labelTaken: "label_taken",
  /** The mode is neither `test` nor `live`. */
  modeInvalid: "mode_invalid",
  /** Ten live credentials already stand for this merchant and mode. */
  limitReached: "credential_limit_reached",
  /** The row the database handed back is not a credential this build wrote. */
  unreadable: "credential_unreadable",
} as const);

/** The audit actions of section 20. Creation is this STEP's; revoking and regeneration are STEP 201's. */
export const CREDENTIAL_AUDIT = Object.freeze({
  created: "api.credential_created",
} as const);

/**
 * One credential as a screen sees it.
 *
 * There is no field here that can hold a key: the display is a handle, a mode and the last four characters,
 * which is exactly what section 20 allows after creation. The signing secret's ciphertext is not here either
 * - not because a screen could decrypt it, but because a shape with no crypto material in it cannot leak one.
 */
export interface CredentialView {
  readonly id: string;
  readonly label: string;
  readonly mode: CredentialMode;
  readonly status: CredentialStatus;
  /** The handle inside the key, shown beside the mode. */
  readonly keyPrefix: string;
  readonly keyLastFour: string;
  /** The whole of what may be shown: `kd_test_shop_••••••••4f2a`. */
  readonly maskedKey: string;
  readonly signingSecretLastFour: string;
  /** The signing secret's own masked display, which has no prefix because none is stored. */
  readonly maskedSigningSecret: string;
  readonly createdAt: string;
  readonly lastUsedAt: string | null;
  readonly revokedAt: string | null;
  readonly revokeReason: string | null;
}

/** What the screen needs to draw section 20: the credentials and the room left to make another. */
export interface CredentialPanelView {
  readonly credentials: readonly CredentialView[];
  /** Live credentials per mode, counted for the limit rather than for the list. */
  readonly counts: Readonly<{ readonly test: number; readonly live: number }>;
  readonly limit: number;
  readonly canCreate: boolean;
  /** True when the merchant holds more rows than the screen reads, so the list says it is a window. */
  readonly truncated: boolean;
}

/** One display row, built from the three columns a key left behind. */
export function maskedKeyOf(input: {
  readonly mode: CredentialMode;
  readonly keyPrefix: string;
  readonly keyLastFour: string;
}): string {
  return `${CREDENTIAL_KEY_PREFIX}_${input.mode}_${input.keyPrefix}_${CREDENTIAL_MASK.repeat(CREDENTIAL_MASK_WIDTH)}${input.keyLastFour}`;
}

/** The signing secret's display, which is four characters and the mask that stands before them. */
export function maskedSigningSecretOf(lastFour: string): string {
  return `${CREDENTIAL_MASK.repeat(CREDENTIAL_MASK_WIDTH)}${lastFour}`;
}
