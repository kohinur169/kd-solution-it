/** What a documented status means for the platform. */
export type StripePaymentOutcome = "paid" | "pending" | "requires_customer_action" | "failed" | "unknown";

/**
 * Map a documented PaymentIntent status to what the platform may act on.
 *
 * Only `succeeded` is paid: the lifecycle page says a `succeeded` intent means "the funds are now in your
 * account and you can confidently fulfill the order", and that a failed attempt returns to
 * `requires_payment_method` rather than to a failure status of its own. `processing` and `requires_capture`
 * are money in flight; `requires_action`, `requires_confirmation` and `requires_payment_method` need the
 * customer; `canceled` is final and not paid. An unrecorded status is `unknown`, never a success.
 */
export function stripePaymentOutcomeOf(status: string): StripePaymentOutcome {
  const normalized = status.trim().toLowerCase();
  if (normalized === "succeeded") return "paid";
  if (normalized === "processing" || normalized === "requires_capture") return "pending";
  if (
    normalized === "requires_action" ||
    normalized === "requires_confirmation" ||
    normalized === "requires_payment_method"
  ) {
    return "requires_customer_action";
  }
  if (normalized === "canceled") return "failed";
  if (STRIPE_PAYMENT_INTENT_STATUSES.includes(normalized)) return "unknown";
  return "unknown";
}

