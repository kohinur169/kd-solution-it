/** Where one attempt stands. */
export type StripeAttemptStatus = "pending" | "created" | "declined" | "rejected" | "unknown";

/** How an attempt finally stood, once a read has settled it. */
export type StripeSettlementStatus = "paid" | "pending" | "requires_customer_action" | "failed";

/** One charge or transfer attempt. Never carries a client secret. */
export interface StripeAttempt {
  readonly id: string;
  readonly kind: StripeAttemptKind;
  readonly companyId: string;
  readonly environment: "sandbox" | "live";
  readonly idempotencyKey: string;
  readonly amountMinor: bigint;
  readonly feeMinor: bigint;
  readonly currency: string;
  readonly destinationAccountId: string;
  /** The `pi_` or `tr_` id, once one exists. */
  readonly providerId: string | null;
  /** The provider's own status string, once it said one. */
  readonly providerStatus: string | null;
  readonly status: StripeAttemptStatus;
  readonly settlement: StripeSettlementStatus | null;
  /** True when a client secret came back; the value itself is never stored. */
  readonly clientSecretIssued: boolean;
  readonly reason: string | null;
  readonly requiresReconciliation: boolean;
  readonly version: number;
  readonly createdAtEpochMs: number;
  readonly updatedAtEpochMs: number;
}

/** The only moves an attempt may make. A row carrying a provider id never leaves `created`. */
export const STRIPE_ATTEMPT_OUTCOMES: Readonly<Record<StripeAttemptStatus, readonly StripeAttemptStatus[]>> =
  deepFreeze({
    pending: ["pending", "created", "declined", "rejected", "unknown"],
    unknown: ["unknown", "created", "rejected", "pending"],
    declined: ["declined"],
    rejected: ["rejected"],
    created: ["created"],
  });

/** The store the caller supplies: one row per attempt, unique on the idempotency key. */
export interface StripeAttemptStore {
  insert(attempt: StripeAttempt): void;
  findById(id: string): StripeAttempt | null;
  findByIdempotencyKey(companyId: string, kind: StripeAttemptKind, idempotencyKey: string): StripeAttempt | null;
  save(next: StripeAttempt, expectedVersion: number): boolean;
}

/** The in-memory store, enforcing the invariants the real table must carry. */
export class InMemoryStripeAttemptStore implements StripeAttemptStore {
  private readonly attempts = new Map<string, StripeAttempt>();

  insert(attempt: StripeAttempt): void {
    if (this.attempts.has(attempt.id)) throw new Error("duplicate attempt id");
    if (attempt.version !== 1) throw new Error("a new attempt starts at version 1");
    if (attempt.status !== "pending") throw new Error("a new attempt is pending");
    if (this.findByIdempotencyKey(attempt.companyId, attempt.kind, attempt.idempotencyKey) !== null) {
      throw new Error("this idempotency key is already used");
    }
    this.attempts.set(attempt.id, attempt);
  }

  findById(id: string): StripeAttempt | null {
    return this.attempts.get(id) ?? null;
  }

  findByIdempotencyKey(
    companyId: string,
    kind: StripeAttemptKind,
    idempotencyKey: string,
  ): StripeAttempt | null {
    return (
      [...this.attempts.values()].find(
        (attempt) =>
          attempt.companyId === companyId && attempt.kind === kind && attempt.idempotencyKey === idempotencyKey,
      ) ?? null
    );
  }

  save(next: StripeAttempt, expectedVersion: number): boolean {
    const current = this.attempts.get(next.id);
    if (current === undefined) return false;
    if (current.companyId !== next.companyId || current.kind !== next.kind) return false;
    if (current.idempotencyKey !== next.idempotencyKey) return false;
    if (current.amountMinor !== next.amountMinor || current.feeMinor !== next.feeMinor) return false;
    if (current.currency !== next.currency || current.destinationAccountId !== next.destinationAccountId) return false;
    if (current.version !== expectedVersion) return false;
    if (next.version !== expectedVersion + 1) return false;
    if (STRIPE_ATTEMPT_OUTCOMES[current.status].includes(next.status) === false) return false;
    if (current.providerId !== null && next.providerId !== current.providerId) return false;
    if (next.status === "created" && next.providerId === null) return false;
    if (current.providerId !== null && next.status !== "created") return false;
    this.attempts.set(next.id, next);
    return true;
  }
}

/** One audit entry this file hands to the caller's audit writer. Never carries a credential or a secret. */
