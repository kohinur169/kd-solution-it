// path: lib/payments/adapters/stripe-payment.ts

/**
 * The Stripe Connect adapter's money movement: destination charges with the platform fee split, the
 * status read that decides whether a charge was paid, and the transfer that pays a connected account.
 *
 * ## What section 6 asks of this provider
 *
 * Section 6: "Stripe Connect: connected sub-merchant account creation, charges and payouts." STEP 163
 * created the account; this is the charge and the payout leg. Section 6 also forbids raw card data on
 * this platform, and Stripe's own documentation says the same thing from the other side: the client
 * secret "can complete the charge", so it must not be logged, embedded in URLs or stored.
 *
 * ## Which charge type, and why it is the one the pages recommend
 *
 * STEP 161 recorded the three charge types. STEP 163 set the connected account's responsibilities to
 * `fees_collector: application` and `losses_collector: application` with `dashboard: none`, and the
 * configuration page says that pair is the recommended configuration **for destination charges**. So the
 * charge is a **destination charge**: created on the platform with `transfer_data[destination]` naming the
 * connected account and `application_fee_amount` naming the platform's fee.
 *
 * The destination-charges page describes exactly what that does: "the full charge amount is immediately
 * transferred from the platform to the `transfer_data[destination]` account after the charge is captured.
 * The `application_fee_amount` (capped at the full amount of the charge) is then transferred back to the
 * platform." Because this platform collects the fees (`fees_collector: application`), the fee it sets must
 * cover both its own fee and Stripe's processing fee — the page says the same, and it is recorded here so
 * STEP 133's fee model is applied knowingly rather than by accident.
 *
 * ## The amount unit, which is the defect worth preventing
 *
 * `lib/payments/money.ts` stores money as a bigint of ten-thousandths (`MONEY_SCALE = 4`), while Stripe
 * counts the smallest currency unit — cents for USD. A fee of 2.90 USD is `29_000` in the platform's
 * scale and `290` to Stripe. Passing the platform number straight through would charge one hundred times
 * the invoice, so the conversion happens exactly once, in `stripeAmountFromPlatformMinor`, which refuses
 * any amount that is not a whole number of cents and any currency the platform does not support. The
 * reverse conversion is how a read answer is compared back to the attempt.
 *
 * ## Idempotency
 *
 * Two guards, because the pages describe two. Stripe's own: an `Idempotency-Key` header of up to 255
 * characters, generated by the client, which returns the first response for a repeated key and errors if
 * the parameters differ. This platform's own: a stored attempt keyed on the same idempotency key, written
 * **before** the call, so a replay answers from the record and never reaches the network. The stored record
 * also survives the 24-hour window after which Stripe may prune its keys.
 *
 * ## What this file is not
 *
 * It does not collect card data: the customer's details go to Stripe's own Payment Element with the
 * publishable key, and this file hands the page a client secret and nothing else. It does not post ledger
 * entries — STEP 132 does that from a confirmed payment, and `applyStripePaymentIntentRead` only reports
 * what the provider said. It receives no webhooks (that is `stripe-webhook.ts`), and it is not a screen.
 */

