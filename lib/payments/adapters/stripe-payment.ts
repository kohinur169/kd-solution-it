/** What creating a charge did. */
export type CreateStripeChargeResult =
  | {
      readonly status: "created";
      readonly attempt: StripeAttempt;
      /** Handed to the payment page once; never stored, logged or audited. */
      readonly clientSecret: string | null;
    }
  | { readonly status: "already_created"; readonly attempt: StripeAttempt; readonly requiresRead: true }
  | { readonly status: "in_flight"; readonly requiresReconciliation: true; readonly reason: string; readonly attempt: StripeAttempt }
  | { readonly status: "declined"; readonly reason: string; readonly declineCode: string | null; readonly attempt: StripeAttempt }
  | { readonly status: "rejected"; readonly reason: string; readonly attempt: StripeAttempt }
  | { readonly status: "failed"; readonly reason: string }
  | { readonly status: "unknown"; readonly requiresReconciliation: true; readonly reason: string; readonly attempt: StripeAttempt };

/**
 * Create a destination charge for a merchant that is ready to take payments.
 *
 * The order is the same discipline STEPs 159 and 163 used: the readiness of the connected account is
 * checked first (a charge on an account whose capabilities are not active is not attempted), the request is
 * validated, the attempt is stored as `pending` **before** the call, and only then is Stripe asked. A replay
 * answers `already_created` without a call, and the caller reads the intent for its status; an `unknown`
 * attempt answers `in_flight`; a `declined` or `rejected` attempt is final, because Stripe either created
 * nothing or created nothing that can be reused.
 */
export async function createStripeCharge(
  request: StripeChargeRequest,
  options: StripePaymentOptions,
): Promise<CreateStripeChargeResult> {
  const readiness = stripeAccountReadinessOf(options.provision);
  if (readiness.canAcceptPayments === false) {
    return {
      status: "failed",
      reason: readiness.blockingReason ?? "the connected account is not ready to accept payments",
    };
  }
  if (options.provision.companyId !== request.companyId) {
    return { status: "failed", reason: "the connected account belongs to another company" };
  }
  if (options.provision.accountId !== null && options.provision.accountId !== request.destinationAccountId) {
    return { status: "failed", reason: "the destination is not this company's connected account" };
  }

  const invalid = validateStripeChargeRequest(request);
  if (invalid !== null) return { status: "failed", reason: invalid };

  const existing = options.attemptStore.findByIdempotencyKey(request.companyId, "charge", request.idempotencyKey);
  if (existing !== null) {
    if (existing.status === "created") return { status: "already_created", attempt: existing, requiresRead: true };
    if (existing.status === "unknown") {
      return {
        status: "in_flight",
        requiresReconciliation: true,
        reason: "an earlier attempt with this key has an unknown outcome; reconcile it before charging again",
        attempt: existing,
      };
    }
    return { status: "failed", reason: "an earlier attempt with this key did not succeed; use a new idempotency key" };
  }

  const configuration = activeConfigurationOf(request.companyId, options);
  if (configuration.ok === false) return { status: "failed", reason: configuration.reason };

  const attempt: StripeAttempt = {
    id: randomUUID(),
    kind: "charge",
    companyId: request.companyId,
    environment: configuration.config.environment,
    idempotencyKey: request.idempotencyKey,
    amountMinor: request.amountMinor,
    feeMinor: request.platformFeeMinor,
    currency: request.currency.trim().toLowerCase(),
    destinationAccountId: request.destinationAccountId,
    providerId: null,
    providerStatus: null,
    status: "pending",
    settlement: null,
    clientSecretIssued: false,
    reason: null,
    requiresReconciliation: false,
    version: 1,
    createdAtEpochMs: options.occurredAtEpochMs,
    updatedAtEpochMs: options.occurredAtEpochMs,
  };

  try {
    options.attemptStore.insert(attempt);
  } catch {
    return { status: "failed", reason: "this idempotency key is already used" };
  }

  let verdict: StripePaymentIntentVerdict;
  try {
    const answer = await (options.transport ?? stripePaymentFetchTransport)({
      method: "POST",
      path: STRIPE_PAYMENT_INTENTS_PATH,
      contentType: "application/x-www-form-urlencoded",
      body: encodeStripeForm(buildStripePaymentIntentBody(request)),
      secretKey: configuration.secretKey,
      apiVersion: configuration.config.apiVersion,
      idempotencyKey: request.idempotencyKey,
    });
    verdict = parseStripePaymentIntentAnswer(answer.status, answer.body);
  } catch {
    verdict = { outcome: "unknown", detail: "the API could not be reached, so a charge may or may not exist" };
  }

  if (verdict.outcome === "created") {
    const created = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "created",
        providerId: verdict.paymentIntentId,
        providerStatus: verdict.status,
        settlement: verdict.paymentOutcome === "paid" ? "paid" : null,
        clientSecretIssued: verdict.clientSecret !== null,
        reason: null,
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_charge.created", created, verdict.paymentOutcome, options);
    return { status: "created", attempt: created, clientSecret: verdict.clientSecret };
  }

  if (verdict.outcome === "declined") {
    const declined = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "declined",
        reason: verdict.detail,
        settlement: "failed",
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_charge.declined", declined, verdict.declineCode ?? "declined", options);
    return { status: "declined", reason: verdict.detail, declineCode: verdict.declineCode, attempt: declined };
  }

  if (verdict.outcome === "rejected") {
    const rejected = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "rejected",
        reason: verdict.detail,
        settlement: "failed",
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_charge.rejected", rejected, "rejected", options);
    return { status: "rejected", reason: verdict.detail, attempt: rejected };
  }

  if (verdict.outcome === "unknown") {
    const unknown = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "unknown",
        reason: verdict.detail,
        requiresReconciliation: true,
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_charge.unknown", unknown, "unknown", options);
    return { status: "unknown", requiresReconciliation: true, reason: verdict.detail, attempt: unknown };
  }

  return { status: "failed", reason: verdict.detail };
}

