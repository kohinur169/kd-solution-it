/** What every call in this file needs. */
export interface StripePaymentOptions {
  readonly provision: StripeAccountProvision;
  readonly configStore: StripeConfigStore;
  readonly keyring: EncryptionKeyring;
  readonly attemptStore: StripeAttemptStore;
  readonly occurredAtEpochMs: number;
  readonly transport?: StripePaymentTransport;
  readonly recordAudit?: (entry: StripePaymentAuditEntry) => void;
}

/** The active configuration opened for one call, or the reason there is none. */
function activeConfigurationOf(
  companyId: string,
  options: StripePaymentOptions,
): { readonly ok: true; readonly config: StripeKeyConfig; readonly secretKey: string } | { readonly ok: false; readonly reason: string } {
  const config = options.configStore.findActiveByCompany(companyId);
  if (config === null) return { ok: false, reason: "no active Stripe key configuration exists for this company" };
  try {
    const secretKey = openSecret(options.keyring, config.secretKeySealed, {
      purpose: "secret",
      scope: stripeSecretKeyScope(companyId),
    });
    return { ok: true, config, secretKey };
  } catch {
    return { ok: false, reason: "the sealed secret key cannot be opened with this keyring" };
  }
}

function audit(
  action: StripePaymentAuditEntry["action"],
  attempt: StripeAttempt,
  outcome: string,
  options: StripePaymentOptions,
): void {
  if (options.recordAudit === undefined) return;
  options.recordAudit({
    action,
    providerKey: STRIPE_PROVIDER_KEY,
    companyId: attempt.companyId,
    attemptId: attempt.id,
    providerId: attempt.providerId,
    environment: attempt.environment,
    outcome,
    occurredAtEpochMs: options.occurredAtEpochMs,
  });
}

function settleAttempt(attempt: StripeAttempt, next: StripeAttempt, options: StripePaymentOptions): StripeAttempt {
  const saved = options.attemptStore.save(next, attempt.version);
  return saved ? next : (options.attemptStore.findById(attempt.id) ?? attempt);
}

