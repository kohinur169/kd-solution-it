  readonly action:
    | "stripe_charge.created"
    | "stripe_charge.declined"
    | "stripe_charge.rejected"
    | "stripe_charge.unknown"
    | "stripe_charge.settled"
    | "stripe_transfer.created"
    | "stripe_transfer.rejected"
    | "stripe_transfer.unknown";
  readonly providerKey: typeof STRIPE_PROVIDER_KEY;
  readonly companyId: string;
  readonly attemptId: string;
  readonly providerId: string | null;
  readonly environment: "sandbox" | "live";
  readonly outcome: string;
  readonly occurredAtEpochMs: number;
