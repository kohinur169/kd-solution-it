/** What a read of one intent said. */
export type ReadStripePaymentIntentResult =
  | {
      readonly status: "read";
      readonly paymentIntentId: string;
      readonly providerStatus: string;
      readonly outcome: StripePaymentOutcome;
      readonly amountMinor: number | null;
      readonly currency: string | null;
      readonly feeMinor: number | null;
      /** The client secret the documented answer carries; handed to the page, never stored. */
      readonly clientSecret: string | null;
    }
  | { readonly status: "failed"; readonly reason: string };

/**
 * Read one intent, which is how a charge is confirmed without trusting the browser.
 *
 * The client confirms the payment, so the browser's word is never enough; the same read is what the webhook
 * receiver (STEP 164's `stripe-webhook.ts`) applies an event through. A failed read says so and never
 * reports a status it did not see.
 */
export async function readStripePaymentIntent(
  paymentIntentId: string,
  options: StripePaymentOptions,
): Promise<ReadStripePaymentIntentResult> {
  if (STRIPE_PAYMENT_INTENT_PATTERN.test(paymentIntentId) === false) {
    return { status: "failed", reason: "the payment intent id is not a documented pi_ id" };
  }
  const configuration = activeConfigurationOf(options.provision.companyId, options);
  if (configuration.ok === false) return { status: "failed", reason: configuration.reason };

  let verdict: StripePaymentIntentVerdict;
  try {
    const answer = await (options.transport ?? stripePaymentFetchTransport)({
      method: "GET",
      path: stripePaymentIntentReadPath(paymentIntentId),
      contentType: "application/x-www-form-urlencoded",
      body: "",
      secretKey: configuration.secretKey,
      apiVersion: configuration.config.apiVersion,
      idempotencyKey: null,
    });
    verdict = parseStripePaymentIntentAnswer(answer.status, answer.body);
  } catch {
    return { status: "failed", reason: "the API could not be reached, so the charge status is unknown" };
  }

  if (verdict.outcome !== "created") {
    const detail: string =
      verdict.outcome === "declined" || verdict.outcome === "rejected" || verdict.outcome === "failed"
        ? verdict.detail
        : "the read did not return a payment intent";
    return { status: "failed", reason: detail };
  }

  return {
    status: "read",
    paymentIntentId: verdict.paymentIntentId,
    providerStatus: verdict.status,
    outcome: verdict.paymentOutcome,
    amountMinor: verdict.amountMinor,
    currency: verdict.currency,
    feeMinor: verdict.feeMinor,
    clientSecret: verdict.clientSecret,
  };
}

/** What applying a read to the attempt it belongs to did. */
export type ApplyStripeReadResult =
  | { readonly status: "applied"; readonly attempt: StripeAttempt; readonly settlement: StripeSettlementStatus }
  | { readonly status: "failed"; readonly reason: string };

/**
 * Apply a read to its attempt, and refuse a read that does not describe it.
 *
 * Only a `succeeded` intent **at the amount, currency and fee the platform asked for** is `paid`. A
 * mismatch is a failure with `requiresReconciliation`, never a paid attempt: the amounts are compared in the
 * platform's own units, which is what stops a currency or unit mix-up becoming a ledger entry.
 */
export function applyStripePaymentIntentRead(
  attempt: StripeAttempt,
  read: Extract<ReadStripePaymentIntentResult, { status: "read" }>,
  options: { readonly occurredAtEpochMs: number; readonly attemptStore: StripeAttemptStore; readonly recordAudit?: (entry: StripePaymentAuditEntry) => void },
): ApplyStripeReadResult {
  if (attempt.providerId !== null && attempt.providerId !== read.paymentIntentId) {
    return { status: "failed", reason: "the read describes another payment intent" };
  }

  const expectedAmount = stripeAmountFromPlatformMinor(attempt.amountMinor, attempt.currency);
  const expectedFee =
    attempt.feeMinor === 0n ? null : stripeAmountFromPlatformMinor(attempt.feeMinor, attempt.currency);

  const amountMatches = expectedAmount.ok === true && read.amountMinor === expectedAmount.amountMinor;
  const currencyMatches = read.currency !== null && read.currency.toLowerCase() === attempt.currency;
  const feeMatches =
    expectedFee === null
      ? read.feeMinor === null || read.feeMinor === 0
      : expectedFee.ok === true && read.feeMinor === expectedFee.amountMinor;

  const mismatch = amountMatches === false || currencyMatches === false || feeMatches === false;
  const settlement: StripeSettlementStatus = mismatch
    ? "failed"
    : read.outcome === "paid"
      ? "paid"
      : read.outcome === "failed"
        ? "failed"
        : read.outcome === "pending"
          ? "pending"
          : "requires_customer_action";

  const next: StripeAttempt = {
    ...attempt,
    providerId: attempt.providerId ?? read.paymentIntentId,
    providerStatus: read.providerStatus,
    settlement,
    reason: mismatch
      ? "the payment intent does not describe this attempt's amount, currency and fee"
      : attempt.reason,
    requiresReconciliation: mismatch,
    version: attempt.version + 1,
    updatedAtEpochMs: options.occurredAtEpochMs,
  };
  const saved = options.attemptStore.save(next, attempt.version);
  if (saved === false) {
    return { status: "failed", reason: "the attempt moved while its read was being applied; re-read it" };
  }

  if (options.recordAudit !== undefined) {
    options.recordAudit({
      action: "stripe_charge.settled",
      providerKey: STRIPE_PROVIDER_KEY,
      companyId: attempt.companyId,
      attemptId: attempt.id,
      providerId: attempt.providerId,
      environment: attempt.environment,
      outcome: settlementOutcomeOf(mismatch, settlement),
      occurredAtEpochMs: options.occurredAtEpochMs,
    });
  }

  return { status: "applied", attempt: next, settlement };
}

function settlementOutcomeOf(mismatch: boolean, settlement: StripeSettlementStatus): string {
  return mismatch ? "mismatch" : settlement;
}

