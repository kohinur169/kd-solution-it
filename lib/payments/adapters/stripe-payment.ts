/* -------------------------------------------------------------------------------------------------
 * The amount conversion, done once
 * ---------------------------------------------------------------------------------------------- */

/** The result of converting a platform amount to a Stripe amount. */
export type StripeAmountConversion =
  | { readonly ok: true; readonly amountMinor: number }
  | { readonly ok: false; readonly reason: string };

/**
 * Convert the platform's bigint minor units to Stripe's smallest currency unit.
 *
 * The platform counts ten-thousandths (`MONEY_SCALE`), Stripe counts cents for USD, so the divisor is
 * `10 ** (MONEY_SCALE - exponent)`. An amount that is not a whole number of cents is refused instead of
 * rounded: rounding money in a payment adapter is how a ledger stops balancing.
 */
export function stripeAmountFromPlatformMinor(minor: bigint, currency: string): StripeAmountConversion {
  const exponent = STRIPE_CURRENCY_EXPONENTS[currency.trim().toLowerCase()];
  if (exponent === undefined) return { ok: false, reason: "the currency is not supported by this adapter" };
  if (minor <= 0n) return { ok: false, reason: "the amount must be greater than zero" };

  const divisor = 10n ** BigInt(MONEY_SCALE - exponent);
  if (minor % divisor !== 0n) {
    return { ok: false, reason: "the amount is not a whole number of the currency's smallest unit" };
  }

  const amount = minor / divisor;
  if (amount > BigInt(STRIPE_MAXIMUM_AMOUNT_MINOR)) return { ok: false, reason: "the amount is too large" };
  return { ok: true, amountMinor: Number(amount) };
}

/** Convert Stripe's smallest currency unit back to the platform's minor units, or null. */
export function stripePlatformMinorFromAmount(amountMinor: number, currency: string): bigint | null {
  const exponent = STRIPE_CURRENCY_EXPONENTS[currency.trim().toLowerCase()];
  if (exponent === undefined) return null;
  if (Number.isInteger(amountMinor) === false || amountMinor < 0) return null;
  return BigInt(amountMinor) * 10n ** BigInt(MONEY_SCALE - exponent);
}

