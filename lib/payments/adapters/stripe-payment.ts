/** What a caller asks to transfer to a connected account, in the platform's money. */
export interface StripeTransferRequest {
  readonly companyId: string;
  readonly amountMinor: bigint;
  readonly currency: string;
  readonly destinationAccountId: string;
  readonly transferGroup: string;
  readonly metadata: Readonly<Record<string, string>>;
  readonly idempotencyKey: string;
}

/** The reason a transfer request is invalid, or null when it is valid. */
export function validateStripeTransferRequest(request: StripeTransferRequest): string | null {
  if (STRIPE_IDEMPOTENCY_KEY_PATTERN.test(request.idempotencyKey) === false) {
    return "the idempotency key must be 16 to 255 characters of letters, digits, dashes or underscores";
  }
  if (STRIPE_ACCOUNT_ID_PATTERN.test(request.destinationAccountId) === false) {
    return "the destination must be a connected account id";
  }
  const amount = stripeAmountFromPlatformMinor(request.amountMinor, request.currency);
  if (amount.ok === false) return amount.reason;
  if (/^[A-Za-z0-9_-]{1,64}$/u.test(request.transferGroup) === false) {
    return "the transfer group must be 1 to 64 letters, digits, dashes or underscores";
  }
  return validateMetadata(request.metadata);
}

/** Build the documented transfer body. */
export function buildStripeTransferBody(request: StripeTransferRequest): Record<string, string> {
  const amount = stripeAmountFromPlatformMinor(request.amountMinor, request.currency);
  const params: Record<string, string> = {
    amount: String(amount.ok === true ? amount.amountMinor : 0),
    currency: request.currency.trim().toLowerCase(),
    destination: request.destinationAccountId,
    transfer_group: request.transferGroup,
  };
  for (const [key, value] of Object.entries(request.metadata)) {
    params[`metadata[${key}]`] = value;
  }
  return params;
}

/** What creating a transfer did. */
export type CreateStripeTransferResult =
  | { readonly status: "created"; readonly attempt: StripeAttempt }
  | { readonly status: "already_created"; readonly attempt: StripeAttempt }
  | { readonly status: "in_flight"; readonly requiresReconciliation: true; readonly reason: string; readonly attempt: StripeAttempt }
  | { readonly status: "rejected"; readonly reason: string; readonly insufficientFunds: boolean; readonly attempt: StripeAttempt }
  | { readonly status: "failed"; readonly reason: string }
  | { readonly status: "unknown"; readonly requiresReconciliation: true; readonly reason: string; readonly attempt: StripeAttempt };

/**
 * Transfer a merchant's balance from the platform account to its connected account.
 *
 * This is this adapter's payout leg: the platform's own payout decision (STEPs 133-141) says how much a
 * merchant is owed, and the transfer moves it. What happens afterwards — the connected account's balance
 * paying out to its bank — is Stripe's payout schedule on the account's `stripe_balance.payouts` capability,
 * which is why the record keeps the transfer id and not a bank reference.
 *
 * The separate-charges page records the risk this call carries: "if you create a transfer and the payment
 * subsequently fails, your platform's balance is debited for the transfer amount. You must then manually
 * reverse the transfer." So the caller's `transferGroup` is required and kept, the amount is not adjustable
 * in place, and an `insufficient_funds` answer is reported as its own fact.
 */
export async function createStripeTransfer(
  request: StripeTransferRequest,
  options: StripePaymentOptions,
): Promise<CreateStripeTransferResult> {
  if (options.provision.companyId !== request.companyId) {
    return { status: "failed", reason: "the connected account belongs to another company" };
  }
  const readiness = stripeAccountReadinessOf(options.provision);
  if (readiness.canAcceptPayments === false) {
    return { status: "failed", reason: readiness.blockingReason ?? "the connected account is not ready" };
  }
  if (options.provision.accountId !== null && options.provision.accountId !== request.destinationAccountId) {
    return { status: "failed", reason: "the destination is not this company's connected account" };
  }

  const invalid = validateStripeTransferRequest(request);
  if (invalid !== null) return { status: "failed", reason: invalid };

  const existing = options.attemptStore.findByIdempotencyKey(request.companyId, "transfer", request.idempotencyKey);
  if (existing !== null) {
    if (existing.status === "created") return { status: "already_created", attempt: existing };
    if (existing.status === "unknown") {
      return {
        status: "in_flight",
        requiresReconciliation: true,
        reason: "an earlier transfer with this key has an unknown outcome; reconcile it before transferring again",
        attempt: existing,
      };
    }
    return { status: "failed", reason: "an earlier transfer with this key did not succeed; use a new idempotency key" };
  }

  const configuration = activeConfigurationOf(request.companyId, options);
  if (configuration.ok === false) return { status: "failed", reason: configuration.reason };

  const attempt: StripeAttempt = {
    id: randomUUID(),
    kind: "transfer",
    companyId: request.companyId,
    environment: configuration.config.environment,
    idempotencyKey: request.idempotencyKey,
    amountMinor: request.amountMinor,
    feeMinor: 0n,
    currency: request.currency.trim().toLowerCase(),
    destinationAccountId: request.destinationAccountId,
    providerId: null,
    providerStatus: null,
    status: "pending",
    settlement: null,
    clientSecretIssued: false,
    reason: null,
    requiresReconciliation: false,
    version: 1,
    createdAtEpochMs: options.occurredAtEpochMs,
    updatedAtEpochMs: options.occurredAtEpochMs,
  };

  try {
    options.attemptStore.insert(attempt);
  } catch {
    return { status: "failed", reason: "this idempotency key is already used" };
  }

  let verdict: StripeTransferVerdict;
  try {
    const answer = await (options.transport ?? stripePaymentFetchTransport)({
      method: "POST",
      path: STRIPE_TRANSFERS_PATH,
      contentType: "application/x-www-form-urlencoded",
      body: encodeStripeForm(buildStripeTransferBody(request)),
      secretKey: configuration.secretKey,
      apiVersion: configuration.config.apiVersion,
      idempotencyKey: request.idempotencyKey,
    });
    verdict = parseStripeTransferAnswer(answer.status, answer.body);
  } catch {
    verdict = { outcome: "unknown", detail: "the API could not be reached, so a transfer may or may not exist" };
  }

  if (verdict.outcome === "created") {
    const expectedAmount = stripeAmountFromPlatformMinor(request.amountMinor, request.currency);
    const matches =
      expectedAmount.ok === true &&
      verdict.amountMinor === expectedAmount.amountMinor &&
      verdict.currency !== null &&
      verdict.currency.toLowerCase() === request.currency.trim().toLowerCase() &&
      verdict.destination === request.destinationAccountId;

    const created = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "created",
        providerId: verdict.transferId,
        providerStatus: "created",
        settlement: matches ? "pending" : "failed",
        reason: matches ? null : "the transfer does not describe this attempt's amount, currency and destination",
        requiresReconciliation: matches === false,
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_transfer.created", created, matches ? "created" : "mismatch", options);
    return { status: "created", attempt: created };
  }

  if (verdict.outcome === "rejected") {
    const rejected = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "rejected",
        reason: verdict.detail,
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_transfer.rejected", rejected, verdict.insufficientFunds ? "insufficient_funds" : "rejected", options);
    return { status: "rejected", reason: verdict.detail, insufficientFunds: verdict.insufficientFunds, attempt: rejected };
  }

  if (verdict.outcome === "unknown") {
    const unknown = settleAttempt(
      attempt,
      {
        ...attempt,
        status: "unknown",
        reason: verdict.detail,
        requiresReconciliation: true,
        version: attempt.version + 1,
        updatedAtEpochMs: options.occurredAtEpochMs,
      },
      options,
    );
    audit("stripe_transfer.unknown", unknown, "unknown", options);
    return { status: "unknown", requiresReconciliation: true, reason: verdict.detail, attempt: unknown };
  }

  return { status: "failed", reason: verdict.detail };
}

