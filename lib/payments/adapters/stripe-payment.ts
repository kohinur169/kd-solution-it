/** What a caller asks to charge, in the platform's money. */
export interface StripeChargeRequest {
  readonly companyId: string;
  /** The captured amount, in the platform's ten-thousandths. */
  readonly amountMinor: bigint;
  /** The platform's fee, in the platform's ten-thousandths. Zero means no application fee. */
  readonly platformFeeMinor: bigint;
  readonly currency: string;
  readonly destinationAccountId: string;
  readonly description: string | null;
  readonly metadata: Readonly<Record<string, string>>;
  readonly idempotencyKey: string;
}

/** The reason a charge request is invalid, or null when it is valid. */
export function validateStripeChargeRequest(request: StripeChargeRequest): string | null {
  if (STRIPE_IDEMPOTENCY_KEY_PATTERN.test(request.idempotencyKey) === false) {
    return "the idempotency key must be 16 to 255 characters of letters, digits, dashes or underscores";
  }
  if (STRIPE_ACCOUNT_ID_PATTERN.test(request.destinationAccountId) === false) {
    return "the destination must be a connected account id";
  }
  const amount = stripeAmountFromPlatformMinor(request.amountMinor, request.currency);
  if (amount.ok === false) return amount.reason;
  if (request.platformFeeMinor < 0n) return "the platform fee cannot be negative";
  if (request.platformFeeMinor >= request.amountMinor) {
    return "the platform fee must be smaller than the amount";
  }
  if (request.platformFeeMinor > 0n) {
    const fee = stripeAmountFromPlatformMinor(request.platformFeeMinor, request.currency);
    if (fee.ok === false) {
      return fee.reason === "the amount is not a whole number of the currency's smallest unit"
        ? "the platform fee must be a whole number of the currency's smallest unit"
        : fee.reason;
    }
  }
  if (request.description !== null) {
    const description = request.description.trim();
    if (description.length === 0) return "a description, when given, must carry text";
    if (description.length > STRIPE_DESCRIPTION_MAXIMUM_LENGTH) return "the description is too long";
    if (carriesCardLikeText(description)) return "a description must not carry card-like digits";
  }
  return validateMetadata(request.metadata);
}

/** The reason metadata is unusable, or null when it is usable. */
export function validateMetadata(metadata: Readonly<Record<string, string>>): string | null {
  const keys = Object.keys(metadata);
  if (keys.length > STRIPE_METADATA_MAXIMUM_ENTRIES) return "a request carries too many metadata entries";
  for (const key of keys) {
    if (STRIPE_METADATA_KEY_PATTERN.test(key) === false) {
      return "a metadata key must be 1 to 40 letters, digits or underscores";
    }
    const value = metadata[key] ?? "";
    if (value.length > STRIPE_METADATA_VALUE_MAXIMUM_LENGTH) return "a metadata value is too long";
    if (carriesCardLikeText(value)) return "a metadata value must not carry card-like digits";
  }
  return null;
}

/**
 * True when a string looks like a card number or a client secret.
 *
 * A payment adapter never receives card data — the Payment Element does — so a value shaped like a PAN or
 * like a `pi_…_secret_…` client secret in an outgoing description or metadata is a defect worth refusing
 * rather than sending and logging.
 */
export function carriesCardLikeText(value: string): boolean {
  const compact = value.replace(/[ -]/gu, "");
  if (/^[0-9]{13,19}$/u.test(compact)) return true;
  if (/\b(?:[0-9]{13,19})\b/u.test(compact)) return true;
  return /_secret_[A-Za-z0-9]{8,}/u.test(value);
}

/** Encode parameters the way the documented curl examples send them. */
export function encodeStripeForm(params: Readonly<Record<string, string>>): string {
  return Object.entries(params)
    .map(([key, value]) => `${encodeURIComponent(key)}=${encodeURIComponent(value)}`)
    .join("&");
}

/**
 * Build the documented destination-charge body.
 *
 * The fields are the page's: `amount`, `currency`, `transfer_data[destination]` and
 * `application_fee_amount`, plus `automatic_payment_methods[enabled]` so the Payment Element can offer the
 * methods the account is enabled for. `confirm` is never sent: the customer confirms in the browser with
 * the client secret, which is the documented flow and keeps card data away from this platform. A zero fee
 * omits `application_fee_amount` entirely, because a zero application fee is not the same request as no
 * application fee.
 */
export function buildStripePaymentIntentBody(request: StripeChargeRequest): Record<string, string> {
  const amount = stripeAmountFromPlatformMinor(request.amountMinor, request.currency);
  const fee =
    request.platformFeeMinor === 0n ? null : stripeAmountFromPlatformMinor(request.platformFeeMinor, request.currency);

  const params: Record<string, string> = {
    amount: String(amount.ok === true ? amount.amountMinor : 0),
    currency: request.currency.trim().toLowerCase(),
    "transfer_data[destination]": request.destinationAccountId,
    "automatic_payment_methods[enabled]": "true",
  };
  if (fee !== null && fee.ok === true) params["application_fee_amount"] = String(fee.amountMinor);
  if (request.description !== null && request.description.trim().length > 0) {
    params["description"] = sanitizeStripeText(request.description).slice(0, STRIPE_DESCRIPTION_MAXIMUM_LENGTH);
  }
  for (const [key, value] of Object.entries(request.metadata)) {
    params[`metadata[${key}]`] = value;
  }
  return params;
}

