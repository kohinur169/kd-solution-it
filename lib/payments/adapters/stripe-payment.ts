/** One call: the method, the path, the body and the credentials. */
export interface StripePaymentCall {
  readonly method: "GET" | "POST";
  readonly path: string;
  readonly contentType: "application/x-www-form-urlencoded";
  readonly body: string;
  readonly secretKey: string;
  readonly apiVersion: string;
  readonly idempotencyKey: string | null;
}

/** The HTTP answer: the status code and the raw body. */
export interface StripePaymentAnswer {
  readonly status: number;
  readonly body: string;
}

/** The transport port. */
export type StripePaymentTransport = (call: StripePaymentCall) => Promise<StripePaymentAnswer>;

/** True when a path is one this file may call. */
export function isStripePaymentPath(path: string): boolean {
  if (path === STRIPE_PAYMENT_INTENTS_PATH || path === STRIPE_TRANSFERS_PATH) return true;
  if (path.startsWith(`${STRIPE_PAYMENT_INTENTS_PATH}/`)) {
    return STRIPE_PAYMENT_INTENT_PATTERN.test(path.slice(STRIPE_PAYMENT_INTENTS_PATH.length + 1));
  }
  return false;
}

/**
 * Performs the documented calls against the documented API base.
 *
 * The path is allowlisted to the two collections and the documented read of one intent; the call is
 * refused without a key, a dated version or a body on a `POST`; redirects are refused; the timeout is
 * bounded and an oversized answer is refused. The `Idempotency-Key` header is sent on every `POST` and
 * never on a `GET`, which is what the idempotency page says.
 */
export const stripePaymentFetchTransport: StripePaymentTransport = async (call) => {
  if (isStripePaymentPath(call.path) === false) throw new Error("invalid API path");
  if (call.secretKey.trim().length === 0) throw new Error("a secret key is required");
  if (call.apiVersion.trim().length === 0) throw new Error("an API version is required");
  if (call.method === "POST" && call.body.length === 0) throw new Error("a request body is required");

  const headers: Record<string, string> = {
    Authorization: `Bearer ${call.secretKey}`,
    Accept: "application/json",
    [STRIPE_API_VERSION_HEADER]: call.apiVersion.trim(),
  };
  if (call.method === "POST") {
    headers["Content-Type"] = call.contentType;
    if (call.idempotencyKey !== null) headers[STRIPE_IDEMPOTENCY_HEADER] = call.idempotencyKey;
  }

  const response = await fetch(stripePaymentEndpointFor(call.path), {
    method: call.method,
    headers,
    ...(call.method === "POST" ? { body: call.body } : {}),
    redirect: "error",
    signal: AbortSignal.timeout(STRIPE_PAYMENT_TIMEOUT_MS),
  });

  const text = await response.text();
  if (text.length > STRIPE_PAYMENT_ANSWER_MAXIMUM_BYTES) throw new Error("invalid API answer");
  return { status: response.status, body: text };
};

/* -------------------------------------------------------------------------------------------------
 * Reading answers
 * ---------------------------------------------------------------------------------------------- */

function parseAnswerBody(body: string): unknown {
  try {
    return body.trim().length === 0 ? null : (JSON.parse(body) as unknown);
  } catch {
    return null;
  }
}

function answerRecord(value: unknown): Readonly<Record<string, unknown>> | null {
  return typeof value === "object" && value !== null ? (value as Readonly<Record<string, unknown>>) : null;
}

function answerString(value: unknown, key: string): string | null {
  const record = answerRecord(value);
  if (record === null) return null;
  const found = record[key];
  return typeof found === "string" ? found : null;
}

function answerNumber(value: unknown, key: string): number | null {
  const record = answerRecord(value);
  if (record === null) return null;
  const found = record[key];
  return typeof found === "number" && Number.isFinite(found) ? found : null;
}

/** Read one provider message out of an answer, sanitised, or the empty string. */
export function stripePaymentMessageOf(payload: unknown): string {
  const record = answerRecord(payload);
  if (record === null) return "";
  const error = answerRecord(record["error"]);
  if (error !== null) {
    for (const key of ["message", "code", "decline_code", "type"]) {
      const value = error[key];
      if (typeof value === "string" && value.trim().length > 0) {
        return sanitizeStripeText(value).slice(0, STRIPE_PAYMENT_TEXT_MAXIMUM_LENGTH);
      }
    }
  }
  for (const key of ["message", "detail"]) {
    const value = record[key];
    if (typeof value === "string" && value.trim().length > 0) {
      return sanitizeStripeText(value).slice(0, STRIPE_PAYMENT_TEXT_MAXIMUM_LENGTH);
    }
  }
  return "";
}

/** The documented decline code of an answer, when there is one. */
export function stripeDeclineCodeOf(payload: unknown): string | null {
  const error = answerRecord(answerRecord(payload)?.["error"]);
  if (error === null) return null;
  for (const key of ["decline_code", "code"]) {
    const value = error[key];
    if (typeof value === "string" && /^[a-z0-9_]{2,64}$/u.test(value)) return value;
  }
  return null;
}

/** What a charge call produced. */
export type StripePaymentIntentVerdict =
  | {
      readonly outcome: "created";
      readonly paymentIntentId: string;
      readonly status: string;
      readonly paymentOutcome: StripePaymentOutcome;
      readonly amountMinor: number | null;
      readonly currency: string | null;
      readonly feeMinor: number | null;
      readonly clientSecret: string | null;
    }
  | { readonly outcome: "declined"; readonly detail: string; readonly declineCode: string | null }
  | { readonly outcome: "rejected"; readonly detail: string }
  | { readonly outcome: "failed"; readonly detail: string }
  | { readonly outcome: "unknown"; readonly detail: string };

/**
 * Read a PaymentIntent answer.
 *
 * `402` is the documented card error, so it is its own outcome: a decline is not a bad request and not a
 * failure of the integration, and its `decline_code` is what a merchant screen shows. `400`, `409` and `422`
 * are `rejected` with the provider's message. `401`, `403`, `404`, `405`, `415` and redirects are `failed`.
 * A timeout-class code, `429`, any `5XX`, a thrown transport or a `2XX` naming no `pi_` id are `unknown`,
 * because a charge may exist.
 */
export function parseStripePaymentIntentAnswer(status: number, body: string): StripePaymentIntentVerdict {
  const payload = parseAnswerBody(body);

  if (status === 408 || status === 425 || status === 429 || status >= 500) {
    return { outcome: "unknown", detail: "the API did not answer finally; a charge may exist" };
  }

  if (status === 402) {
    const message = stripePaymentMessageOf(payload);
    return {
      outcome: "declined",
      detail: message.length > 0 ? message : "the card was declined",
      declineCode: stripeDeclineCodeOf(payload),
    };
  }

  if (status === 400 || status === 409 || status === 422) {
    const message = stripePaymentMessageOf(payload);
    return {
      outcome: "rejected",
      detail: message.length > 0 ? message : `Stripe refused the charge with status ${status}`,
    };
  }

  if (status === 401 || status === 403) {
    const message = stripePaymentMessageOf(payload);
    return { outcome: "failed", detail: message.length > 0 ? message : "the API rejected the key" };
  }

  if (status >= 300 && status < 400) {
    return { outcome: "failed", detail: "the API answered with a redirect, which proves nothing" };
  }

  if (status < 200 || status >= 300) {
    const message = stripePaymentMessageOf(payload);
    return { outcome: "failed", detail: message.length > 0 ? message : `the API refused the call with status ${status}` };
  }

  const id = answerString(payload, "id");
  if (id === null || STRIPE_PAYMENT_INTENT_PATTERN.test(id) === false) {
    return { outcome: "unknown", detail: "the answer names no payment intent, so a charge may or may not exist" };
  }

  const intentStatus = answerString(payload, "status") ?? "";
  return {
    outcome: "created",
    paymentIntentId: id,
    status: intentStatus,
    paymentOutcome: stripePaymentOutcomeOf(intentStatus),
    amountMinor: answerNumber(payload, "amount"),
    currency: answerString(payload, "currency"),
    feeMinor: answerNumber(payload, "application_fee_amount"),
    clientSecret: answerString(payload, "client_secret"),
  };
}

/** What a transfer call produced. */
export type StripeTransferVerdict =
  | {
      readonly outcome: "created";
      readonly transferId: string;
      readonly amountMinor: number | null;
      readonly currency: string | null;
      readonly destination: string | null;
    }
  | { readonly outcome: "rejected"; readonly detail: string; readonly insufficientFunds: boolean }
  | { readonly outcome: "failed"; readonly detail: string }
  | { readonly outcome: "unknown"; readonly detail: string };

/**
 * Read a transfer answer.
 *
 * The documented failure this endpoint has is the platform's own balance: "your Stripe balance must be able
 * to cover the transfer amount, or you'll receive an 'Insufficient Funds' error". That error is a `400` with
 * the documented code, and it is reported as a `rejected` answer that says so, because it is a real fact
 * about the platform's balance rather than a bad request from this code.
 */
export function parseStripeTransferAnswer(status: number, body: string): StripeTransferVerdict {
  const payload = parseAnswerBody(body);
  const message = stripePaymentMessageOf(payload);
  const code = stripeDeclineCodeOf(payload);

  if (status === 408 || status === 425 || status === 429 || status >= 500) {
    return { outcome: "unknown", detail: "the API did not answer finally; a transfer may exist" };
  }

  if (status === 400 || status === 409 || status === 422) {
    const insufficient = code === "balance_insufficient";
    return {
      outcome: "rejected",
      detail:
        message.length > 0
          ? message
          : insufficient
            ? "the platform balance cannot cover this transfer"
            : `Stripe refused the transfer with status ${status}`,
      insufficientFunds: insufficient,
    };
  }

  if (status === 401 || status === 403) {
    return { outcome: "failed", detail: message.length > 0 ? message : "the API rejected the key" };
  }

  if (status >= 300 && status < 400) {
    return { outcome: "failed", detail: "the API answered with a redirect, which proves nothing" };
  }

  if (status < 200 || status >= 300) {
    return {
      outcome: "failed",
      detail: message.length > 0 ? message : `the API refused the transfer with status ${status}`,
    };
  }

  const id = answerString(payload, "id");
  if (id === null || STRIPE_TRANSFER_PATTERN.test(id) === false) {
    return { outcome: "unknown", detail: "the answer names no transfer, so a transfer may or may not exist" };
  }

  return {
    outcome: "created",
    transferId: id,
    amountMinor: answerNumber(payload, "amount"),
    currency: answerString(payload, "currency"),
    destination: answerString(payload, "destination"),
  };
}

