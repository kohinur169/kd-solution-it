-- STEP 032 - the editable email templates of section 23: one row per activity email.
--
-- Section 23 lists the twenty activity emails and says super_admin edits their templates. The
-- vocabulary is closed here, so a typo in a service call cannot invent a twenty first event that
-- silently never sends, and the key is unique per locale, so one event has exactly one English
-- template today and can gain a translation without a schema change.
--
-- A template is retired with `is_active = false`, never deleted: `email_send_logs` records a
-- template key, and a row that vanished would leave a sent email pointing at nothing. The guard
-- freezes the key and the locale, because a row is the template of one event and not a slot to
-- be repointed at another, and it refuses any soft delete for the reason above.

begin;

create function public.email_templates_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' then
    if new.template_key is distinct from old.template_key
       or new.locale is distinct from old.locale then
      raise exception 'a template keeps its event and its locale'
        using errcode = 'check_violation';
    end if;

    if new.deleted_at is not null then
      raise exception 'a template is retired with is_active, not deleted'
        using errcode = 'check_violation';
    end if;
  end if;

  return new;
end;
$$;

comment on function public.email_templates_guard_state() is
  'Keeps a template on its event and locale, and retires it with is_active, not a delete.';

create table public.email_templates (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid,
  template_key text not null,
  locale text not null default 'en',
  subject text not null,
  body text not null,
  is_active boolean not null default true,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint email_templates_pkey primary key (id),
  constraint email_templates_company_fkey foreign key (company_id)
    references public.companies (id),
  constraint email_templates_created_by_fkey foreign key (created_by)
    references public.users (id),
  constraint email_templates_platform_check check (company_id is null),
  constraint email_templates_key_check check (
    template_key in ('welcome', 'email_verification', 'password_reset', 'login_lock_alert',
                     'new_device_alert', 'kyc_submitted', 'kyc_approved', 'kyc_rejected',
                     'invoice_sent', 'payment_received', 'payment_failed', 'refund_update',
                     'dispute_update', 'payout_sent', 'settlement_released',
                     'subscription_warning', 'service_stop', 'service_restore',
                     'support_reply', 'account_unlock')
  ),
  constraint email_templates_locale_check check (locale ~ '^[a-z]{2}(-[A-Z]{2})?$'),
  constraint email_templates_subject_check check (
    char_length(subject) between 1 and 160
    and subject = btrim(subject)
  ),
  constraint email_templates_body_check check (char_length(body) between 1 and 20000),
  constraint email_templates_updated_check check (updated_at >= created_at),
  constraint email_templates_deleted_check check (deleted_at is null or deleted_at >= created_at),
  constraint email_templates_row_version_check check (version > 0)
);

comment on table public.email_templates is
  'One editable template per activity email of section 23, per locale.';

comment on column public.email_templates.id is
  'UUID v7 primary key. Time ordered, generated by public.uuid_generate_v7().';

comment on column public.email_templates.company_id is
  'Always null: the templates are the platform templates of section 23.';

comment on column public.email_templates.template_key is
  'The activity email this template renders, from the twenty keys of section 23.';

comment on column public.email_templates.locale is
  'The language of this template, en by default; the key and the locale are unique together.';

comment on column public.email_templates.subject is
  'The subject line, 1 to 160 characters, stored trimmed.';

comment on column public.email_templates.body is
  'The body an editor saves, with the placeholders the sending service replaces.';

comment on column public.email_templates.is_active is
  'True while the template sends; false retires it without deleting the row.';

comment on column public.email_templates.created_by is
  'The super_admin who first wrote the template.';

comment on column public.email_templates.created_at is
  'When the row was written.';

comment on column public.email_templates.updated_at is
  'Set by the email_templates_set_row_metadata trigger on every update.';

comment on column public.email_templates.deleted_at is
  'Present for the schema rule; the guard refuses a value, because a template is retired instead.';

comment on column public.email_templates.version is
  'Optimistic locking counter, incremented by the email_templates_set_row_metadata trigger.';

-- One template per event and locale, so a second row cannot shadow the first.
create unique index email_templates_key
  on public.email_templates (template_key, locale);

-- The editor lists the live templates of one locale, most recently changed first.
create index email_templates_active_idx
  on public.email_templates (is_active, updated_at desc)
  where deleted_at is null;

create trigger email_templates_guard_state
  before insert or update on public.email_templates
  for each row
  execute function public.email_templates_guard_state();

create trigger email_templates_set_row_metadata
  before update on public.email_templates
  for each row
  execute function public.set_row_metadata();

alter table public.email_templates enable row level security;

create policy email_templates_default_deny
  on public.email_templates
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
