-- One live service per code inside one merchant. A deleted service releases its code.
create unique index services_code_key
  on public.services (company_id, lower(code))
  where deleted_at is null and code is not null;

-- The paginated list of section 15: newest first, with the id breaking ties inside one timestamp.
create index services_page_idx
  on public.services (company_id, created_at desc, id desc)
  where deleted_at is null;

-- Lookup and sort by the name the merchant typed, case insensitively.
create index services_name_idx on public.services (company_id, lower(name))
  where deleted_at is null;

create trigger services_set_row_metadata
  before update on public.services
  for each row
  execute function public.set_row_metadata();

alter table public.services enable row level security;

create policy services_default_deny
