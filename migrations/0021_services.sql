-- STEP 020 - the work a merchant sells by the hour or the project, from section 15.
--
-- Section 15 names products and services in one sentence and section 16 prices them the same way, so
-- this table repeats the money rules of `products` exactly: `unit_price_minor` in minor units next to
-- a three letter `currency`, never a float, never negative, zero allowed. What differs is identity:
-- a product has a SKU, a service has a code, and the default unit is `hour` rather than `item`,
-- because the common case for work is not "one of these".
--
-- The unit vocabulary is the same closed list as `products`: `item`, `unit`, `hour`, `day`, `week`,
-- `month`, `project`. One list for both tables is deliberate, because the invoice prints the quantity
-- and the word together and a line must read the same whichever catalogue row produced it.
--
-- `code` is optional, shaped, and unique per merchant under `lower()` while the row is not deleted;
-- the index does not count a deleted row, so a typo can be removed and the code entered again. As with
-- `clients` and `products`, delete is a soft delete: an invoice line points here and must stay
-- explainable after the service is retired.

begin;

create table public.services (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  name text not null,
  code text,
  description text,
  unit_price_minor bigint not null,
  currency text not null default 'USD',
  unit text not null default 'hour',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint services_pkey primary key (id),
  constraint services_company_fkey foreign key (company_id) references public.companies (id),
  constraint services_name_check check (
    char_length(name) between 1 and 160 and name = btrim(name)
  ),
  constraint services_code_check check (
    code is null or code ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,47}$'
  ),
  constraint services_description_check check (
    description is null
    or (char_length(description) between 1 and 2000 and description = btrim(description))
  ),
  constraint services_price_check check (unit_price_minor >= 0),
  constraint services_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint services_unit_check check (
    unit in ('item', 'unit', 'hour', 'day', 'week', 'month', 'project')
  ),
  constraint services_version_positive_check check (version > 0),
  constraint services_updated_after_creation_check check (updated_at >= created_at),
  constraint services_deleted_after_creation_check
    check (deleted_at is null or deleted_at >= created_at)
);

