-- path: migrations/0001_companies.sql
-- STEP 012 - the tenant root.
--
-- `companies` is the row every later table points at, so it is the first table the platform
-- creates. It carries the six audit columns the feature list requires on every table: id (UUID
-- v7), company_id, created_at, updated_at, deleted_at and version, with row level security
-- enabled and an explicit default-deny policy.
--
-- The row is its own tenant, so company_id is a stored generated column equal to id. That keeps
-- the rule "every table has company_id" literally true, gives later queries one column name to
-- join on, and avoids a self-referencing foreign key that would have to be deferred on insert.
--
-- Only the identity of a company lives here. Status, country, plan, branding, KYC and suspension
-- belong to the STEPs that own those features and arrive as later migrations; a column added now
-- would be a guess about someone else's scope.
--
-- PostgreSQL before 18 has no native UUID v7, so this migration defines one. It is a real v7:
-- 48 bits of millisecond timestamp, version nibble 7, variant bits 10, and 74 random bits from
-- `gen_random_uuid()`. Ids therefore sort by creation time without a sequence and without
-- revealing a row count.
--
-- The file is one transaction: applied by `psql -f` it either lands whole or not at all.

begin;

-- A UUID v7 for the current millisecond.
--
-- `search_path` is empty and every call is schema qualified, so the function behaves the same for
-- any role and cannot be redirected by a caller that sets its own search path.
create function public.uuid_generate_v7()
returns uuid
language plpgsql
volatile
set search_path = ''
as $$
declare
  unix_ts_ms bytea;
  uuid_bytes bytea;
begin
  unix_ts_ms := pg_catalog.substr(
    pg_catalog.int8send(
      (pg_catalog.date_part('epoch', pg_catalog.clock_timestamp()) * 1000)::bigint
    ),
    3
  );

  uuid_bytes := pg_catalog.uuid_send(pg_catalog.gen_random_uuid());

  -- Bytes 1-6 become the millisecond timestamp; `overlay` keeps bytes 7-16 random.
  uuid_bytes := pg_catalog.overlay(uuid_bytes, unix_ts_ms, 1, 6);

  -- Byte 7 keeps its low nibble and takes the version nibble 0111 (7).
  uuid_bytes := pg_catalog.set_byte(
    uuid_bytes,
    6,
    (b'0111' || pg_catalog.get_byte(uuid_bytes, 6)::bit(4))::bit(8)::integer
  );

  -- Byte 9 keeps its low six bits and takes the RFC 4122 variant bits 10.
  uuid_bytes := pg_catalog.set_byte(
    uuid_bytes,
    8,
    (b'10' || pg_catalog.get_byte(uuid_bytes, 8)::bit(6))::bit(8)::integer
  );

  return pg_catalog.encode(uuid_bytes, 'hex')::uuid;
end;
$$;

comment on function public.uuid_generate_v7() is
  'UUID v7 from the current millisecond and a random tail. Used as the id default of every table.';

-- Keeps updated_at and the optimistic locking counter honest on every update.
--
-- The application still writes `where id = $1 and version = $2`, so a stale writer fails; this
-- trigger makes the counter monotonic even for a hand written update, and removes updated_at from
-- every call site. A row that is not actually updated never fires it.
create function public.set_row_metadata()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  new.version := old.version + 1;

  return new;
end;
$$;

comment on function public.set_row_metadata() is
  'Before-update trigger: sets updated_at to now() and increments version.';

create table public.companies (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid generated always as (id) stored not null,
  name text not null,
  slug text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint companies_pkey primary key (id),
  constraint companies_name_length_check check (char_length(name) between 1 and 120),
  constraint companies_name_trimmed_check check (name = btrim(name)),
  constraint companies_slug_format_check check (slug ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$'),
  constraint companies_version_positive_check check (version > 0),
  constraint companies_updated_after_creation_check check (updated_at >= created_at),
  constraint companies_deleted_after_creation_check
    check (deleted_at is null or deleted_at >= created_at)
);

comment on table public.companies is
  'The tenant root. One row per merchant company; every later table points here through company_id.';

comment on column public.companies.id is
  'UUID v7 primary key. Time ordered, generated by public.uuid_generate_v7().';

comment on column public.companies.company_id is
  'The tenant of this row. Generated from id, because this row is the tenant.';

comment on column public.companies.name is
  'Business display name, trimmed, 1 to 120 characters. Never empty and never padded.';

comment on column public.companies.slug is
  'Lowercase URL-safe identifier, unique among rows that are not deleted.';

comment on column public.companies.deleted_at is
  'Soft delete marker. A company row is never removed, because history points at it.';

comment on column public.companies.version is
  'Optimistic locking counter. Incremented by the companies_set_row_metadata trigger.';

-- A slug becomes available again only after the row that held it is deleted.
create unique index companies_slug_key on public.companies (slug) where deleted_at is null;

create trigger companies_set_row_metadata
  before update on public.companies
  for each row
  execute function public.set_row_metadata();

-- Row level security: on, and explicitly denied until a STEP adds the policy that grants access.
-- An explicit policy is readable in the catalog and provable; "no policy at all" relies on the
-- reader knowing that the default is deny.
alter table public.companies enable row level security;

create policy companies_default_deny
  on public.companies
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
