-- STEP 026 - the rolling reserve of section 10.
--
-- The reserve is the merchant's own money kept back for risk and negative balance protection. Section
-- 10 fixes its two numbers as super_admin settings: the percent withheld and the days before a release.
-- They are columns here rather than a config read at release time, because a reserve agreement is a
-- fact about a merchant and not about today's setting; the percent is stored in basis points, so 5.00
-- percent is 500 and no float is involved.
--
-- `held_minor` and `released_minor` are the running account, bounded by one check so the released total
-- can never pass what was withheld. Each release writes a ledger entry whose `source_id` is this row,
-- which is how the section 10 release days stay a rule of the ledger instead of a column that moves.
--
-- One merchant has one active reserve: the partial unique index says so while paused and closed rows
-- stay as history. A closed reserve carries its instant and is locked by `reserves_guard_state`, while
-- the percent, the release days, the currency and the start instant never change on any row.

begin;

create function public.reserves_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.company_id is distinct from old.company_id
     or new.percent_bps is distinct from old.percent_bps
     or new.release_days is distinct from old.release_days
     or new.currency is distinct from old.currency
     or new.started_at is distinct from old.started_at then
    raise exception 'a reserve keeps its merchant, its percent, its days and its start'
      using errcode = 'check_violation';
  end if;

  if old.status = 'closed'
     and (to_jsonb(new) - 'updated_at' - 'version')
         is distinct from (to_jsonb(old) - 'updated_at' - 'version') then
    raise exception 'a closed reserve is history'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.reserves_guard_state() is
  'Freezes the terms of a reserve and locks it once closed.';

create table public.reserves (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  percent_bps integer not null,
  release_days integer not null,
  currency text not null default 'USD',
  held_minor bigint not null default 0,
  released_minor bigint not null default 0,
  status text not null default 'active',
  started_at timestamptz not null default now(),
  next_release_on timestamptz,
  closed_at timestamptz,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint reserves_pkey primary key (id),
  constraint reserves_company_fkey foreign key (company_id) references public.companies (id),
  constraint reserves_percent_check check (percent_bps between 0 and 10000),
  constraint reserves_days_check check (release_days between 1 and 365),
  constraint reserves_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint reserves_held_check check (held_minor >= 0 and released_minor >= 0),
  constraint reserves_released_check check (released_minor <= held_minor),
  constraint reserves_status_check check (status in ('active', 'paused', 'closed')),
  constraint reserves_closed_instant_check check ((status = 'closed') = (closed_at is not null)),
  constraint reserves_next_release_check check (
    next_release_on is null or next_release_on > started_at
  ),
  constraint reserves_note_check check (
    note is null
    or (
      char_length(note) between 1 and 280
      and note = btrim(note)
    )
  ),
  constraint reserves_row_version_check check (version > 0),
  constraint reserves_updated_check check (updated_at >= created_at),
  constraint reserves_deleted_check check (deleted_at is null or deleted_at >= created_at)
);

