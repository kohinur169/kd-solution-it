-- One merchant holds one active reserve; paused and closed rows stay as history.
create unique index reserves_active_key
  on public.reserves (company_id)
  where status = 'active' and deleted_at is null;

-- The release job of section 10: what is due, nearest first.
create index reserves_release_idx
  on public.reserves (next_release_on)
  where status = 'active' and deleted_at is null;

create trigger reserves_guard_state
  before update on public.reserves
  for each row
  execute function public.reserves_guard_state();

create trigger reserves_set_row_metadata
  before update on public.reserves
  for each row
  execute function public.set_row_metadata();

alter table public.reserves enable row level security;

