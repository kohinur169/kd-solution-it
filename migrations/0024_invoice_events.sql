-- STEP 021 - the timeline of one invoice.
--
-- Section 16 gives an invoice a lifecycle: created, sent, viewed, paid, voided, duplicated, reminded.
-- Section 19 asks for a chargeback evidence pack that includes the invoice and the communication
-- record, and a support call months later needs to say when the document was sent and when the client
-- first opened it. A single `updated_at` cannot answer either question, so every step is a row.
--
-- The table is append only in the strongest sense the database offers: `invoice_events_guard_append_only`
-- refuses every update and every delete, whatever role asks, exactly as `audit_logs` does. History
-- that can be edited is not evidence, and the `version` column therefore stays 1 for ever.
--
-- `actor` names who acted from a closed vocabulary (`merchant`, `client`, `office`, `system`) and
-- `actor_user_id` names the person when there was one; a system event may not carry a user, because
-- that would blame a person for a scheduled job.
--
-- The tenant is enforced the same way as on the lines: the event points at its invoice through the
-- pair `(invoice_id, company_id)`, so a row cannot join another merchant's document.

begin;

create function public.invoice_events_guard_append_only()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'invoice events are append only'
    using errcode = 'check_violation';
end;
$$;

comment on function public.invoice_events_guard_append_only() is
  'Refuses every update and every removal of an invoice event, so the timeline cannot be rewritten.';

create table public.invoice_events (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  invoice_id uuid not null,
  type text not null,
  actor text not null default 'system',
  actor_user_id uuid,
  detail text,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint invoice_events_pkey primary key (id),
  constraint invoice_events_company_fkey foreign key (company_id) references public.companies (id),
  constraint invoice_events_invoice_fkey foreign key (invoice_id, company_id)
    references public.invoices (id, company_id),
  constraint invoice_events_actor_user_fkey foreign key (actor_user_id) references public.users (id),
  constraint invoice_events_type_check check (
    type in ('created', 'sent', 'viewed', 'payment_received', 'paid', 'overdue_reminder', 'voided',
             'duplicated', 'note')
  ),
  constraint invoice_events_actor_check check (
    actor in ('merchant', 'client', 'office', 'system')
  ),
  constraint invoice_events_actor_user_check check (
    actor <> 'system' or actor_user_id is null
  ),
  constraint invoice_events_detail_check check (
    detail is null or (char_length(detail) between 1 and 500 and detail = btrim(detail))
  ),
  constraint invoice_events_version_positive_check check (version > 0),
  constraint invoice_events_updated_after_creation_check check (updated_at >= created_at),
  constraint invoice_events_deleted_after_creation_check
    check (deleted_at is null or deleted_at >= created_at)
);

comment on table public.invoice_events is
  'The append only timeline of an invoice: what happened, when, and who did it.';

comment on column public.invoice_events.id is
  'UUID v7 primary key. Time ordered, generated by public.uuid_generate_v7().';

comment on column public.invoice_events.company_id is
  'The merchant. Equal to the invoice tenant through the composite foreign key.';

comment on column public.invoice_events.invoice_id is
  'The invoice this event belongs to, referenced together with company_id.';

comment on column public.invoice_events.type is
  'created, sent, viewed, payment_received, paid, overdue_reminder, voided, duplicated or note.';

comment on column public.invoice_events.actor is
  'merchant, client, office or system, the closed list of who can act on an invoice.';

comment on column public.invoice_events.actor_user_id is
  'The signed in person behind the event, null for a system job and for a client link.';

comment on column public.invoice_events.detail is
  'Optional sentence for a person, trimmed, at most 500 characters, never card data.';

comment on column public.invoice_events.occurred_at is
  'When the event happened, defaulting to now(). Also the sort key of the timeline.';

comment on column public.invoice_events.created_at is
  'When the row was written. Never after the event it records in normal use.';

comment on column public.invoice_events.updated_at is
  'Present for shape only: no update is possible on this table.';

comment on column public.invoice_events.deleted_at is
  'Present for shape only: no removal is possible on this table.';

comment on column public.invoice_events.version is
  'Optimistic locking counter, always 1 because the guard trigger refuses every update.';

-- The timeline of one invoice, newest first, with the id breaking ties inside one microsecond.
create index invoice_events_timeline_idx
  on public.invoice_events (invoice_id, occurred_at desc, id desc);

-- The job question of section 27: which reminders or views happened for one merchant, and when.
create index invoice_events_type_idx
  on public.invoice_events (company_id, type, occurred_at desc);

create trigger invoice_events_guard_append_only
  before update or delete on public.invoice_events
  for each row
  execute function public.invoice_events_guard_append_only();

alter table public.invoice_events enable row level security;

create policy invoice_events_default_deny
  on public.invoice_events
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
