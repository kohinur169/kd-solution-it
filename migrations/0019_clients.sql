-- STEP 020 - the clients a merchant invoices, from section 15.
--
-- Section 15 says "Client create, edit, delete and paginated list", and section 25 gives the owner
-- of a business the management of "own business, clients, products, invoices, payments". A client is
-- therefore a tenant row: `company_id` is `not null`, two merchants may hold the same person without
-- sharing anything, and every read of this table is by `company_id` first.
--
-- Delete means soft delete. STEP 021 will reference a client from an invoice and an invoice is kept
-- for years, so the row is never removed: `deleted_at` marks it, the row stays explainable, and the
-- partial unique index stops counting it, which is what lets a merchant remove a mistyped client and
-- reuse the address on the section 15 CSV import.
--
-- An email is unique per merchant and not per platform. The unique index is built on `lower(email)`
-- rather than on a `citext` column, because this folder creates no extension (rule 9): `Sam@Example.com`
-- and `sam@example.com` are one client to one merchant, and two merchants never collide.
--
-- The address is one thing, not five independent fields. A city, a region, a postal code or a country
-- without `address_line1` is refused, because that is the row a CSV import produces when a column is
-- shifted, and an invoice that prints a city with no street is worse than an invoice with no address.
--
-- Everything the row carries is bounded and trimmed: nothing here may be blank, padded, or long
-- enough to be a pasted document. `tax_id` is the client's own tax identifier, which the TaxCloud
-- STEP of section 7 reads; the tax engine itself is not this STEP.

begin;

create table public.clients (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  name text not null,
  company_name text,
  email text,
  phone text,
  address_line1 text,
  address_line2 text,
  city text,
  region text,
  postal_code text,
  country text,
  tax_id text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint clients_pkey primary key (id),
  constraint clients_company_fkey foreign key (company_id) references public.companies (id),
  constraint clients_name_check check (
    char_length(name) between 1 and 120 and name = btrim(name)
  ),
  constraint clients_company_name_check check (
    company_name is null
    or (char_length(company_name) between 1 and 160 and company_name = btrim(company_name))
  ),
  constraint clients_email_check check (
    email is null
    or (
      char_length(email) between 3 and 254
      and email = btrim(email)
      and email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$'
    )
  ),
  constraint clients_phone_check check (
    phone is null
    or (phone = btrim(phone) and phone ~ '^[+]?[0-9][0-9 ().-]{4,30}$')
  ),
  constraint clients_address_line1_check check (
    address_line1 is null
    or (char_length(address_line1) between 1 and 160 and address_line1 = btrim(address_line1))
  ),
  constraint clients_address_line2_check check (
    address_line2 is null
    or (char_length(address_line2) between 1 and 160 and address_line2 = btrim(address_line2))
  ),
  constraint clients_city_check check (
    city is null or (char_length(city) between 1 and 80 and city = btrim(city))
  ),
  constraint clients_region_check check (
    region is null or (char_length(region) between 1 and 80 and region = btrim(region))
  ),
  constraint clients_postal_code_check check (
    postal_code is null or postal_code ~ '^[A-Za-z0-9][A-Za-z0-9 -]{1,14}[A-Za-z0-9]$'
  ),
  constraint clients_country_check check (country is null or country ~ '^[A-Z]{2}$'),
  constraint clients_address_complete_check check (
    num_nonnulls(address_line2, city, region, postal_code, country) = 0
    or address_line1 is not null
  ),
  constraint clients_tax_id_check check (
    tax_id is null or (char_length(tax_id) between 1 and 32 and tax_id = btrim(tax_id))
  ),
  constraint clients_notes_check check (
    notes is null or (char_length(notes) between 1 and 2000 and notes = btrim(notes))
  ),
  constraint clients_version_positive_check check (version > 0),
  constraint clients_updated_after_creation_check check (updated_at >= created_at),
  constraint clients_deleted_after_creation_check
    check (deleted_at is null or deleted_at >= created_at)
);

comment on table public.clients is
  'The people and businesses one merchant invoices. Tenant scoped, soft deleted, never removed.';

comment on column public.clients.id is
