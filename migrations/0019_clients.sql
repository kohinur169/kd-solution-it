comment on column public.clients.company_id is
  'The merchant that owns this client. Two merchants hold the same person as two separate rows.';

comment on column public.clients.name is
  'The person to address on the invoice, trimmed, 1 to 120 characters.';

comment on column public.clients.company_name is
  'The client business name when there is one, trimmed, at most 160 characters.';

comment on column public.clients.email is
  'Invoice delivery address, at most 254 characters, unique per merchant while the row is live.';

comment on column public.clients.phone is
  'Optional contact number: digits with an optional leading plus, spaces, brackets, dot or hyphen.';

comment on column public.clients.address_line1 is
  'Street line. Required as soon as any other address field is set.';

comment on column public.clients.address_line2 is
  'Second street line, such as a suite or a floor; optional.';

