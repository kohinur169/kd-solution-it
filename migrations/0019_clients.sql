-- One client per address per merchant. Lower case, and a deleted client releases the address.
create unique index clients_email_key
  on public.clients (company_id, lower(email))
  where deleted_at is null and email is not null;

-- The paginated list of section 15: newest first, with the id breaking ties so a page boundary is
-- stable while two rows share a timestamp.
create index clients_page_idx
  on public.clients (company_id, created_at desc, id desc)
  where deleted_at is null;

-- Lookup and sort by the name the merchant typed, case insensitively.
create index clients_name_idx on public.clients (company_id, lower(name))
  where deleted_at is null;

create trigger clients_set_row_metadata
  before update on public.clients
  for each row
  execute function public.set_row_metadata();

alter table public.clients enable row level security;

create policy clients_default_deny
  on public.clients
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
