-- One position per mode: the match order is total, so no payment has two first matches.
create unique index routing_rules_priority_key
  on public.routing_rules (mode, priority)
  where deleted_at is null;

-- One name per mode, case insensitive, so the panel cannot hold two rows called the same thing.
create unique index routing_rules_name_key
  on public.routing_rules (mode, lower(rule_name))
  where deleted_at is null;

-- The decision itself: the active rules of one mode, in the order the caller walks them.
create index routing_rules_match_idx
  on public.routing_rules (mode, country_code, payment_method, priority)
  where status = 'active' and deleted_at is null;

create trigger routing_rules_guard_provider
  before insert or update on public.routing_rules
