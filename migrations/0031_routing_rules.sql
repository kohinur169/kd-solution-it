-- STEP 023 - the routing rules of section 6.
--
-- "Routing rules decide the provider. When no routing rule matches, the payment is rejected and is
-- never silently sent to another provider." Two things follow from that sentence and both are
-- structural here.
--
-- The first is that a rule names exactly one provider: `provider_id` is not null, and the guard below
-- refuses a rule that points at a provider that is disabled or that cannot accept a payment. A rule
-- that could not work is worse than no rule, because it would reject a payment the panel believed it
-- had routed.
--
-- The second is that there is no fallback. This table has no `default_provider`, no `fallback`, no
-- `is_default` and no "try next" column, so a writer cannot quietly route an unmatched payment
-- somewhere else: an unmatched payment has no rule and is rejected by the caller, which is exactly
-- what the feature list asks for.
--
-- The criteria are the three a payment actually carries at decision time: the payer's country, the
-- payment method and the amount band. Each is optional, `priority` orders the matches and is unique
-- per mode, so the first match is unambiguous and the list has no ties. `mode` keeps section 8's test
-- and live routes apart, so a sandbox payment can never take the live route.
--
-- Like the provider catalogue this is a platform object: the platform routes, the merchant does not,
-- so `company_id` is null on every row.

begin;

create function public.routing_rules_guard_provider()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  provider_state text;
  provider_accepts boolean;
begin
  select status, supports_acceptance into provider_state, provider_accepts
  from public.payment_providers where id = new.provider_id;

  if provider_state is distinct from 'enabled' then
    raise exception 'a routing rule needs an enabled provider'
      using errcode = 'check_violation';
  end if;

  if provider_accepts is not true then
    raise exception 'a routing rule needs a provider that accepts payments'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.routing_rules_guard_provider() is
  'Refuses a routing rule whose provider is disabled or cannot accept a payment.';

create table public.routing_rules (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid,
  rule_name text not null,
  mode text not null default 'test',
  priority integer not null,
  provider_id uuid not null,
  country_code text,
  payment_method text,
  min_amount_minor bigint,
  max_amount_minor bigint,
  status text not null default 'active',
  disabled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint routing_rules_pkey primary key (id),
  constraint routing_rules_company_fkey foreign key (company_id) references public.companies (id),
  constraint routing_rules_provider_fkey foreign key (provider_id)
    references public.payment_providers (id),
  constraint routing_rules_platform_check check (company_id is null),
  constraint routing_rules_name_check check (
    char_length(rule_name) between 1 and 80 and rule_name = btrim(rule_name)
  ),
  constraint routing_rules_mode_check check (mode in ('test', 'live')),
  constraint routing_rules_priority_check check (priority between 1 and 999),
  constraint routing_rules_country_check check (
    country_code is null or country_code ~ '^[A-Z]{2}$'
  ),
  constraint routing_rules_method_check check (
    payment_method is null or payment_method in ('card', 'bank_transfer', 'e_wallet')
  ),
  constraint routing_rules_minimum_check check (
    min_amount_minor is null or min_amount_minor >= 0
  ),
  constraint routing_rules_maximum_check check (
    max_amount_minor is null
    or (max_amount_minor > 0 and (min_amount_minor is null or max_amount_minor >= min_amount_minor))
  ),
  constraint routing_rules_status_check check (status in ('active', 'disabled')),
  constraint routing_rules_disabled_check check (
    (status = 'disabled') = (disabled_at is not null)
  ),
  constraint routing_rules_row_version_check check (version > 0),
  constraint routing_rules_updated_check check (updated_at >= created_at),
  constraint routing_rules_deleted_check check (deleted_at is null or deleted_at >= created_at)
);

