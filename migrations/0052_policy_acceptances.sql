-- STEP 028 - the accepted policies of section 3.
--
-- Section 3 publishes twelve policies: KYC and KYB, UBO, AML and CFT, sanctions and PEP,
-- underwriting, merchant acceptance, chargeback, refund and settlement, fraud and risk, data
-- privacy, PCI-DSS and automated decision review. The twelve keys are the closed vocabulary of
-- `policy_key`, so a typo cannot invent a thirteenth policy.
--
-- An acceptance is evidence of a version, not a column on the merchant. A row keeps the key, the
-- version text, the SHA-256 of the accepted text, the person and the instant; the unique key over
-- merchant, policy and version means accepting version 3 twice is one row while accepting version
-- 4 is a second row, which is exactly what an audit asks. `accepted_at` is the instant the person
-- accepted, so it is never after the row that records it.
--
-- The text is not stored. The hash is enough to prove which text was accepted, and the text itself
-- belongs to the policy page that published it. `policy_acceptances_guard_state` freezes the whole
-- acceptance, so a recorded consent is never rewritten; a new version is a new row.

begin;

create function public.policy_acceptances_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.company_id is distinct from old.company_id
     or new.policy_key is distinct from old.policy_key
     or new.policy_version is distinct from old.policy_version
     or new.document_sha256 is distinct from old.document_sha256
     or new.accepted_at is distinct from old.accepted_at
     or new.accepted_by is distinct from old.accepted_by then
    raise exception 'an accepted policy keeps its version, its text hash and its person'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.policy_acceptances_guard_state() is
  'Freezes the policy, its version, its hash, the person and the instant of an acceptance.';

create table public.policy_acceptances (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  policy_key text not null,
  policy_version text not null,
  document_sha256 text not null,
  accepted_at timestamptz not null default now(),
  accepted_by uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint policy_acceptances_pkey primary key (id),
  constraint policy_acceptances_company_fkey foreign key (company_id)
    references public.companies (id),
  constraint policy_acceptances_accepted_by_fkey foreign key (accepted_by)
    references public.users (id),
  constraint policy_acceptances_key_check check (
    policy_key in ('kyc_kyb', 'ubo', 'aml_cft', 'sanctions_pep', 'underwriting',
                   'merchant_acceptance', 'chargeback', 'refund_settlement', 'fraud_risk',
                   'data_privacy', 'pci_dss', 'automated_decision_review')
  ),
  constraint policy_acceptances_version_check check (
    char_length(policy_version) between 1 and 40
    and policy_version = btrim(policy_version)
    and policy_version ~ '^[0-9]{1,4}([.][0-9]{1,4}){0,3}$'
  ),
  constraint policy_acceptances_hash_check check (document_sha256 ~ '^[0-9a-f]{64}$'),
  constraint policy_acceptances_instant_check check (accepted_at <= created_at),
  constraint policy_acceptances_row_version_check check (version > 0),
  constraint policy_acceptances_updated_check check (updated_at >= created_at),
  constraint policy_acceptances_deleted_check check (
    deleted_at is null or deleted_at >= created_at
  )
);

comment on table public.policy_acceptances is
  'One acceptance of one policy version by one person of one merchant.';

comment on column public.policy_acceptances.id is
  'UUID v7 primary key. Time ordered, generated by public.uuid_generate_v7().';

comment on column public.policy_acceptances.company_id is
  'The merchant whose person accepted the policy. Frozen after the row is written.';

comment on column public.policy_acceptances.policy_key is
  'One of the twelve policies of section 3, from a closed vocabulary.';

comment on column public.policy_acceptances.policy_version is
  'The version text of the accepted policy, such as 3 or 3.1.4.';

comment on column public.policy_acceptances.document_sha256 is
  'SHA-256 of the accepted text, 64 lower case hex, so the exact text is provable.';

comment on column public.policy_acceptances.accepted_at is
  'When the person accepted the policy. Never after the row that records it.';

comment on column public.policy_acceptances.accepted_by is
  'The person who accepted, a user of the merchant.';

comment on column public.policy_acceptances.created_at is
  'When the row was written.';

comment on column public.policy_acceptances.updated_at is
  'Maintained by public.set_row_metadata() on every update.';

comment on column public.policy_acceptances.deleted_at is
  'Soft delete marker. A withdrawn acceptance frees its version for a fresh row.';

comment on column public.policy_acceptances.version is
  'Optimistic concurrency counter, incremented by public.set_row_metadata().';

-- One acceptance per merchant, policy and version, while the row is live.
create unique index policy_acceptances_version_key
  on public.policy_acceptances (company_id, policy_key, policy_version)
  where deleted_at is null;

-- Which version of a policy a merchant last accepted.
create index policy_acceptances_policy_idx
  on public.policy_acceptances (policy_key, company_id, accepted_at desc)
  where deleted_at is null;

create trigger policy_acceptances_guard_state
  before update on public.policy_acceptances
  for each row
  execute function public.policy_acceptances_guard_state();

create trigger policy_acceptances_set_row_metadata
  before update on public.policy_acceptances
  for each row
  execute function public.set_row_metadata();

alter table public.policy_acceptances enable row level security;

create policy policy_acceptances_default_deny
  on public.policy_acceptances
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
