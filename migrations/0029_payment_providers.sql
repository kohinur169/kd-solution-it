-- One live row per adapter name, and one live row per position on the panel.
create unique index payment_providers_key_key
  on public.payment_providers (provider_key)
  where deleted_at is null;

create unique index payment_providers_order_key
  on public.payment_providers (display_order)
  where deleted_at is null;

create trigger payment_providers_set_row_metadata
  before update on public.payment_providers
  for each row
  execute function public.set_row_metadata();

alter table public.payment_providers enable row level security;

create policy payment_providers_default_deny
  on public.payment_providers
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
