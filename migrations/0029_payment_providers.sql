comment on column public.payment_providers.company_id is
  'Null on every row: the provider catalogue belongs to the platform, as plans do.';

comment on column public.payment_providers.provider_key is
  'The adapter name: nmi, payoneer, rainforest, stripe_connect or airwallex. Closed vocabulary.';

comment on column public.payment_providers.display_name is
  'The name the super admin page shows, trimmed, 1 to 80 characters.';

comment on column public.payment_providers.supports_acceptance is
  'True when the adapter can accept a payment: NMI, Rainforest, Stripe Connect and Airwallex.';

comment on column public.payment_providers.supports_payouts is
  'True when the adapter can pay a merchant out: Payoneer, Stripe Connect and Airwallex.';

