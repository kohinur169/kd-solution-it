-- STEP 023 - the five payment providers of section 6.
--
-- Section 6 names them: NMI, Payoneer, Rainforest, Stripe Connect and Airwallex. Each one has an
-- adapter file in code and a row here, and the row is what the super admin gateway page reads when it
-- lists, tests, enables and disables a provider without a redeploy.
--
-- The catalogue is a platform object, not a merchant one: `company_id` is null on every row, exactly
-- as `plans` is in `0014`, and the check states it rather than leaving it to convention. A merchant
-- does not choose its processor in this platform; the routing rules of `0031` do, and section 6 keeps
-- that decision with the platform.
--
-- `provider_key` is a closed vocabulary of the five adapters. That is the database half of "a
-- provider without an adapter in code cannot be added from the dashboard": a sixth name needs a
-- sixth adapter and a new migration, so the panel can never offer a provider the registry cannot
-- call.
--
-- The capability matrix is three booleans rather than a list of words, because the three questions
-- the platform actually asks are "can it accept a card", "can it pay a merchant out" and "can it
-- create a sub-merchant". A check refuses a row where all three are false, so a catalogue entry that
-- can do nothing cannot exist.
--
-- "A provider cannot be enabled when its connection test fails" is a check, not a habit of the
-- settings screen: `status = 'enabled'` requires `last_test_ok = true` and the instant the test ran.
-- Disabling clears `enabled_at`, so the two states cannot drift apart.

begin;

create table public.payment_providers (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid,
  provider_key text not null,
  display_name text not null,
  supports_acceptance boolean not null default false,
  supports_payouts boolean not null default false,
  supports_submerchant boolean not null default false,
  status text not null default 'disabled',
  display_order integer not null,
  enabled_at timestamptz,
  last_tested_at timestamptz,
  last_test_ok boolean,
  last_test_detail text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint payment_providers_pkey primary key (id),
  constraint payment_providers_company_fkey foreign key (company_id) references public.companies (id),
  constraint payment_providers_platform_check check (company_id is null),
  constraint payment_providers_key_check check (
    provider_key in ('nmi', 'payoneer', 'rainforest', 'stripe_connect', 'airwallex')
  ),
  constraint payment_providers_display_name_check check (
    char_length(display_name) between 1 and 80 and display_name = btrim(display_name)
  ),
  constraint payment_providers_capability_check check (
    supports_acceptance or supports_payouts or supports_submerchant
  ),
  constraint payment_providers_status_check check (status in ('disabled', 'enabled')),
  constraint payment_providers_enabled_check check (
    (status = 'enabled') = (enabled_at is not null)
  ),
  constraint payment_providers_test_check check (
    status <> 'enabled' or (last_test_ok is true and last_tested_at is not null)
  ),
  constraint payment_providers_test_detail_check check (
    last_test_detail is null
    or (
      char_length(last_test_detail) between 1 and 280
      and last_test_detail = btrim(last_test_detail)
    )
  ),
  constraint payment_providers_order_check check (display_order between 1 and 999),
  constraint payment_providers_version_check check (version > 0),
  constraint payment_providers_updated_check check (updated_at >= created_at),
  constraint payment_providers_deleted_check check (
    deleted_at is null or deleted_at >= created_at
  )
);

comment on table public.payment_providers is
