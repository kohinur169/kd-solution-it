-- STEP 032 - the messages of a support ticket of section 24, one row per reply.
--
-- Section 24 asks for replies by email and for attachments a merchant can add. A message is a
-- row that is never changed: the guard refuses every update and every delete, because a reply
-- that was emailed to a person cannot be edited afterwards without calling the record a lie. A
-- correction is a new message, which is also what the customer received.
--
-- The direction and the channel are separate, because a message can arrive through the portal or
-- by email and can be a merchant's or the office's. An email message carries its provider message
-- id, an outbound message carries its author, and the attachment is one `files` row of the
-- `support_attachment` purpose; a second attachment is a second message, which is the limit this
-- STEP records rather than a join table no screen of STEP 228-229 shows.
--
-- The insert checks that the ticket belongs to the same merchant. `support_tickets` has no unique
-- key over `(id, company_id)` a composite foreign key could point at, so the rule is a lookup in
-- the guard, the same shape the uploader check of `files` uses.

begin;

create function public.support_ticket_messages_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform 1 from public.support_tickets
    where id = new.ticket_id and company_id = new.company_id;

    if not found then
      raise exception 'a support message belongs to the merchant of its ticket'
        using errcode = 'check_violation';
    end if;

    return new;
  end if;

  raise exception 'a support message is append only'
    using errcode = 'check_violation';
end;
$$;

comment on function public.support_ticket_messages_guard_state() is
  'Refuses a message of another merchant, and refuses every update and every delete.';

create table public.support_ticket_messages (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  ticket_id uuid not null,
  author_user_id uuid,
  direction text not null,
  channel text not null default 'portal',
  body text not null,
  file_id uuid,
  email_message_id text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint support_ticket_messages_pkey primary key (id),
  constraint support_ticket_messages_company_fkey foreign key (company_id)
    references public.companies (id),
  constraint support_ticket_messages_ticket_fkey foreign key (ticket_id)
    references public.support_tickets (id),
  constraint support_ticket_messages_author_fkey foreign key (author_user_id)
    references public.users (id),
  constraint support_ticket_messages_file_fkey foreign key (file_id)
    references public.files (id),
  constraint support_ticket_messages_direction_check check (
    direction in ('inbound', 'outbound')
  ),
  constraint support_ticket_messages_channel_check check (channel in ('portal', 'email')),
  constraint support_ticket_messages_body_check check (
    char_length(body) between 1 and 20000
  ),
  constraint support_ticket_messages_email_check check (
    email_message_id is null
    or (
      char_length(email_message_id) between 1 and 255
      and email_message_id = btrim(email_message_id)
    )
  ),
  constraint support_ticket_messages_email_channel_check check (
    channel <> 'email' or email_message_id is not null
  ),
  constraint support_ticket_messages_outbound_check check (
    direction <> 'outbound' or author_user_id is not null
  ),
  constraint support_ticket_messages_sent_check check (
    sent_at is null or sent_at >= created_at
  ),
  constraint support_ticket_messages_updated_check check (updated_at >= created_at),
  constraint support_ticket_messages_deleted_check check (
    deleted_at is null or deleted_at >= created_at
  ),
  constraint support_ticket_messages_row_version_check check (version > 0)
);

