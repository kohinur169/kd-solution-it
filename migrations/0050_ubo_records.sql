-- STEP 028 - the beneficial owners of section 3's UBO policy.
--
-- The policy says an owner of 25 percent or more is a UBO, so the share is stored in basis points and
-- `is_significant` is true exactly at 2500 or above. Two checks hold that: one bounds the share between
-- 1 and 10000 basis points, and one ties the flag to the number, so a 10 percent owner cannot be
-- labelled significant and a 40 percent owner cannot be labelled small.
--
-- `ubo_records_guard_total` sums the owners of one submission and refuses a row that would take the
-- total above 10000 basis points, which is the 100 percent of a company. It runs on insert and on
-- update and ignores the row being written, so an owner can be corrected downward but the file as a
-- whole cannot claim more of the business than exists.
--
-- The identity document is a hash, never a number. Section 4 lists "identity document number hash" as
-- one of the duplicate signals, so `id_document_sha256` is 64 lower case hex characters and nothing
-- else, and it is frozen with the rest of the identity by `ubo_records_guard_state`.

begin;

create function public.ubo_records_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.company_id is distinct from old.company_id
     or new.submission_id is distinct from old.submission_id
     or new.full_name is distinct from old.full_name
     or new.date_of_birth is distinct from old.date_of_birth
     or new.country is distinct from old.country
     or new.ownership_bps is distinct from old.ownership_bps
     or new.id_document_sha256 is distinct from old.id_document_sha256 then
    raise exception 'a UBO keeps its merchant, its name, its share and its document hash'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.ubo_records_guard_state() is
  'Freezes the identity and the share of a beneficial owner.';

create function public.ubo_records_guard_total()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  already_owned integer;
begin
  select coalesce(sum(ownership_bps), 0) into already_owned
  from public.ubo_records
  where submission_id = new.submission_id and id <> new.id and deleted_at is null;

  if already_owned + new.ownership_bps > 10000 then
    raise exception 'the owners of a submission cannot add up to more than 100 percent'
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.ubo_records_guard_total() is
  'Keeps the beneficial owners of one submission within 10000 basis points.';

create table public.ubo_records (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  submission_id uuid not null,
  full_name text not null,
  date_of_birth date not null,
  country text not null,
  ownership_bps integer not null,
  is_significant boolean not null,
  id_document_sha256 text not null,
  is_pep boolean not null default false,
  screened_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint ubo_records_pkey primary key (id),
  constraint ubo_records_company_fkey foreign key (company_id) references public.companies (id),
  constraint ubo_records_submission_fkey foreign key (submission_id, company_id)
    references public.kyc_submissions (id, company_id),
  constraint ubo_records_name_check check (
    char_length(full_name) between 2 and 160 and full_name = btrim(full_name)
  ),
  constraint ubo_records_birth_check check (date_of_birth >= date '1900-01-01'),
  constraint ubo_records_country_check check (country ~ '^[A-Z]{2}$'),
  constraint ubo_records_share_check check (ownership_bps between 1 and 10000),
  constraint ubo_records_significant_check check (is_significant = (ownership_bps >= 2500)),
  constraint ubo_records_hash_check check (id_document_sha256 ~ '^[0-9a-f]{64}$'),
  constraint ubo_records_screened_check check (
    screened_at is null or screened_at >= created_at
  ),
  constraint ubo_records_row_version_check check (version > 0),
  constraint ubo_records_updated_check check (updated_at >= created_at),
  constraint ubo_records_deleted_check check (deleted_at is null or deleted_at >= created_at)
);

