comment on column public.cms_pages.company_id is
  'Always null: the public pages belong to the platform, not to a merchant.';

comment on column public.cms_pages.slug is
  'The url segment of the page, lower case with single hyphens, unique among live pages.';

comment on column public.cms_pages.title is
  'The page title, 1 to 160 characters, stored trimmed.';

comment on column public.cms_pages.body is
  'The page content an editor saves, up to 200000 characters.';

comment on column public.cms_pages.policy_key is
  'The policy this page carries, from the twelve keys of policy_acceptances, null for other pages.';

comment on column public.cms_pages.status is
  'draft or published. A published page carries its instant and its person.';

comment on column public.cms_pages.seo_title is
  'The title the metadata generator of STEP 237 uses, up to 70 characters.';

comment on column public.cms_pages.seo_description is
  'The description that generator uses, up to 320 characters.';

comment on column public.cms_pages.published_at is
  'When the page last went live, required by the published state.';

comment on column public.cms_pages.published_by is
  'The person who made it live, required by the published state.';

comment on column public.cms_pages.created_by is
  'The person who first wrote the page.';

comment on column public.cms_pages.created_at is
  'When the row was written.';

comment on column public.cms_pages.updated_at is
  'Set by the cms_pages_set_row_metadata trigger on every update.';

comment on column public.cms_pages.deleted_at is
  'Soft delete marker, set once; the guard refuses it while the page is published.';

comment on column public.cms_pages.version is
  'Optimistic locking counter, incremented by the cms_pages_set_row_metadata trigger.';

-- One live page per slug, so the sitemap never sees the same url twice.
create unique index cms_pages_slug_key
  on public.cms_pages (slug)
  where deleted_at is null;

-- One live page per policy, so a merchant is never shown two versions of one promise.
create unique index cms_pages_policy_key
  on public.cms_pages (policy_key)
  where policy_key is not null and deleted_at is null;

-- The sitemap and the admin list: published pages, most recently published first.
create index cms_pages_published_idx
  on public.cms_pages (status, published_at desc)
  where deleted_at is null;

create trigger cms_pages_guard_state
  before insert or update on public.cms_pages
  for each row
  execute function public.cms_pages_guard_state();

create trigger cms_pages_set_row_metadata
  before update on public.cms_pages
  for each row
  execute function public.set_row_metadata();

alter table public.cms_pages enable row level security;

create policy cms_pages_default_deny
  on public.cms_pages
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
