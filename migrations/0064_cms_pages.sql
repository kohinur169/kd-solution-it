-- path: migrations/0064_cms_pages.sql
-- STEP 032 - the CMS pages of section 25: one row per public page, editable from the office.
--
-- Section 25 makes every public page editable through the CMS and names the pages: Home, Product,
-- Pricing, Company, Legal, Support, Blog, Contact and the policy pages. This table is that set.
-- A page is identified by its slug rather than by a fixed list, so the sitemap of STEP 237 reads
-- every published row and no new page needs a migration.
--
-- Section 3 asks for the policies as CMS editable pages with versioned merchant acceptance, and
-- `policy_acceptances` already closes their twelve keys. `policy_key` reuses that list, is null
-- for a page that is not a policy, and is unique among live rows, so one policy cannot have two
-- pages competing for the acceptance link and a typo cannot invent a thirteenth policy.
--
-- A page is `draft` or `published`. The published pair is the instant and the person, so a page
-- cannot be live without a record of who made it live, and the SEO pair is stored beside the body
-- for the metadata generator. `cms_pages_guard_state` freezes the slug and the policy key, and
-- refuses a delete of a published page, because the acceptance records of section 3 point at the
-- page a merchant read.

begin;

create function public.cms_pages_guard_state()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' then
    if new.slug is distinct from old.slug
       or new.policy_key is distinct from old.policy_key then
      raise exception 'a page keeps its slug and its policy key'
        using errcode = 'check_violation';
    end if;

    if old.status = 'published' and new.deleted_at is not null then
      raise exception 'a published page is unpublished before it is deleted'
        using errcode = 'check_violation';
    end if;
  end if;

  return new;
end;
$$;

comment on function public.cms_pages_guard_state() is
  'Keeps a page on its slug and its policy key, and refuses a delete while it is published.';

create table public.cms_pages (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid,
  slug text not null,
  title text not null,
  body text not null,
  policy_key text,
  status text not null default 'draft',
  seo_title text,
  seo_description text,
  published_at timestamptz,
  published_by uuid,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint cms_pages_pkey primary key (id),
  constraint cms_pages_company_fkey foreign key (company_id) references public.companies (id),
  constraint cms_pages_published_by_fkey foreign key (published_by) references public.users (id),
  constraint cms_pages_created_by_fkey foreign key (created_by) references public.users (id),
  constraint cms_pages_platform_check check (company_id is null),
  constraint cms_pages_slug_check check (
    char_length(slug) between 1 and 80
    and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
  ),
  constraint cms_pages_title_check check (
    char_length(title) between 1 and 160
    and title = btrim(title)
  ),
  constraint cms_pages_body_check check (char_length(body) between 1 and 200000),
  constraint cms_pages_policy_key_check check (
    policy_key is null
    or policy_key in ('kyc_kyb', 'ubo', 'aml_cft', 'sanctions_pep', 'underwriting',
                      'merchant_acceptance', 'chargeback', 'refund_settlement', 'fraud_risk',
                      'data_privacy', 'pci_dss', 'automated_decision_review')
  ),
  constraint cms_pages_status_check check (status in ('draft', 'published')),
  constraint cms_pages_published_check check (
    (status = 'published') = (published_at is not null and published_by is not null)
  ),
  constraint cms_pages_seo_title_check check (
    seo_title is null
    or (
      char_length(seo_title) between 1 and 70
      and seo_title = btrim(seo_title)
    )
  ),
  constraint cms_pages_seo_description_check check (
    seo_description is null
    or (
      char_length(seo_description) between 1 and 320
      and seo_description = btrim(seo_description)
    )
  ),
  constraint cms_pages_updated_check check (updated_at >= created_at),
  constraint cms_pages_deleted_check check (deleted_at is null or deleted_at >= created_at),
  constraint cms_pages_row_version_check check (version > 0)
);

comment on table public.cms_pages is
  'One public page of section 25, draft or published, with its SEO metadata and its policy key.';

comment on column public.cms_pages.id is
