-- STEP 020 - the goods a merchant sells, from section 15.
--
-- Section 15 pairs "Product and service create, edit, delete and paginated list", but a product and a
-- service are not the same thing to the person who fills the form: a product is a good with a SKU and
-- a unit count, a service is work billed by time. They are therefore two tables with the same money
-- rules and different identities, and STEP 021's line item points at whichever one the merchant chose
-- while carrying a snapshot of the name and the price, so a later price change cannot rewrite an
-- invoice that was already sent.
--
-- `unit_price_minor` is a `bigint` of minor units and never a float, next to an explicit three letter
-- `currency`, exactly as `plans` does it. Zero is allowed, because a complimentary line is a real
-- invoice line; negative is not.
--
-- `sku` is optional and unique per merchant under `lower()`. It is optional because a merchant may
-- sell three things without ever naming them, and it is unique only while the row is not deleted, so a
-- typo can be removed and the same code entered again.
--
-- `unit` is one closed vocabulary shared with `services`: `item`, `unit`, `hour`, `day`, `week`,
-- `month`, `project`. The invoice prints the quantity and this word together, so "2 hour" has to be
-- spelled the same way everywhere; a merchant that needs a new word gets a migration, not a typo.
--
-- As with `clients`, delete means soft delete: an invoice written in 2026 must still explain which
-- product produced its line.

begin;

create table public.products (
  id uuid not null default public.uuid_generate_v7(),
  company_id uuid not null,
  name text not null,
  sku text,
  description text,
  unit_price_minor bigint not null,
  currency text not null default 'USD',
  unit text not null default 'item',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  version integer not null default 1,
  constraint products_pkey primary key (id),
  constraint products_company_fkey foreign key (company_id) references public.companies (id),
  constraint products_name_check check (
    char_length(name) between 1 and 160 and name = btrim(name)
  ),
  constraint products_sku_check check (
    sku is null or sku ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,47}$'
  ),
  constraint products_description_check check (
    description is null
    or (char_length(description) between 1 and 2000 and description = btrim(description))
  ),
  constraint products_price_check check (unit_price_minor >= 0),
  constraint products_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint products_unit_check check (
    unit in ('item', 'unit', 'hour', 'day', 'week', 'month', 'project')
  ),
  constraint products_version_positive_check check (version > 0),
  constraint products_updated_after_creation_check check (updated_at >= created_at),
  constraint products_deleted_after_creation_check
    check (deleted_at is null or deleted_at >= created_at)
);

