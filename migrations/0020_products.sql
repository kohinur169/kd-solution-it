-- One live product per code inside one merchant. A deleted product releases its code.
create unique index products_sku_key
  on public.products (company_id, lower(sku))
  where deleted_at is null and sku is not null;

-- The paginated list of section 15: newest first, with the id breaking ties inside one timestamp.
create index products_page_idx
  on public.products (company_id, created_at desc, id desc)
  where deleted_at is null;

-- Lookup and sort by the name the merchant typed, case insensitively.
create index products_name_idx on public.products (company_id, lower(name))
  where deleted_at is null;

create trigger products_set_row_metadata
  before update on public.products
  for each row
  execute function public.set_row_metadata();

alter table public.products enable row level security;

create policy products_default_deny
  on public.products
  as permissive
  for all
  to public
  using (false)
  with check (false);

commit;
